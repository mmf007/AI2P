using MudBlazor;

namespace AI2P.UI.Services;

/// <summary>
/// Настройки окон-ФОРМ (ТЗ гл. 11, T-9-S1).
///
/// Умолчание MudBlazor — окно закрывается щелчком по затемнению ВОКРУГ него
/// (<c>DialogOptions.BackdropClick</c>), причём закрывается отменой: всё введённое пропадает.
/// Для формы задачи это ловушка — промах мимо окна (а ещё чаще: выделение текста в описании
/// мышью с отпусканием кнопки за краем окна) отменяет работу целиком и без переспроса.
///
/// Поэтому формы, в которые человек что-то ВВОДИТ, открываются с этими настройками:
/// щелчок мимо окна не делает ничего, закрыть можно кнопкой «Отмена» и клавишей Escape —
/// то есть намеренным действием.
///
/// Окна, в которых вводить нечего (просмотр документа модели, список файлов, переспрос),
/// умолчания не меняют: там закрытие щелчком мимо удобно и терять нечего.
/// </summary>
public static class FormDialogs
{
    /// <summary>
    /// Настройки окна-формы: заданная ширина во всю доступную и НЕЗАКРЫВАЕМОЕ затемнение.
    /// </summary>
    /// <param name="maxWidth">Предельная ширина окна — как в прежних вызовах.</param>
    public static DialogOptions Options(MaxWidth maxWidth) => new()
    {
        MaxWidth = maxWidth,
        FullWidth = true,
        // T-9-S1: промах мимо окна не должен отменять форму
        BackdropClick = false,
    };
}
