          name        TEXT NOT NULL DEFAULT '',       -- имя для человека
          is_current  INTEGER NOT NULL DEFAULT 0,     -- текущий — ровно один и он последний
          rules_mode  TEXT NOT NULL DEFAULT 'common', -- как перенесены правила архивации (T-41-S0)
          created_by  TEXT REFERENCES executors(id),  -- кто создал
          created_at  TEXT NOT NULL,
          updated_at  TEXT NOT NULL,
          deleted_at  TEXT
        );

        -- СОСТОЯНИЕ АРХИВА НА КОНКРЕТНОМ СЕРВЕРЕ (T-40-S0) — открыт (лежит каталогом),
        -- закрыт (лежит одним .zip) или удалён с этого сервера. НЕ реплицируется (её нет
        -- в ChangeLog.OrgTables), и это не оптимизация, а требование ТЗ: открыть, закрыть
        -- и удалить архив каждый сервер решает сам — на одном он распакован для просмотра,
        -- на другом лежит запакованным, а на третьем его нет вовсе. Устроена по образцу
        -- run_requests_applied и notification_marks — собственная память сервера.
        --
        -- Строки может не быть вовсе (архив приехал репликацией, а файлов его здесь нет) —
        -- тогда состояние выводится из файловой системы: есть каталог — открыт, есть .zip —
        -- закрыт, нет ничего — удалён (ArchiveService.StateOf)
        CREATE TABLE IF NOT EXISTS archive_states (
          archive_id TEXT NOT NULL,
          server_id  TEXT NOT NULL,
          state      TEXT NOT NULL DEFAULT 'closed', -- ArchiveStates: open/closed/deleted
          updated_at TEXT NOT NULL,
          PRIMARY KEY (archive_id, server_id)
        );

        -- ГДЕ АРХИВ ЕСТЬ (T-47-S0, выпуск 1.105). Удаление архива на каждом сервере СВОЁ и
        -- не реплицируется, но в общем списке надо отметить, на каких серверах архив есть, —
        -- иначе неоткуда взять список источников для скачивания. Поэтому наличие едет
        -- ОТДЕЛЬНОЙ строкой, по образцу ai_model_servers и project_servers: свою строку
        -- пишет только сам сервер, партнёру она едет как сведение «у меня он есть».
        --
        -- Это НЕ состояние archive_states: открыт архив здесь или закрыт, соседей не касается
        -- и не реплицируется никогда. Здесь только «есть / нет»
        CREATE TABLE IF NOT EXISTS archive_servers (
          id         TEXT PRIMARY KEY,               -- <archive_id>|<server_id>
          archive_id TEXT NOT NULL REFERENCES archives(id),
          server_id  TEXT NOT NULL,                  -- unid сервера; он в СЕРВЕРНОЙ БД, FK невозможен
          has_copy   INTEGER NOT NULL DEFAULT 0,     -- 1 — архив на этом сервере есть (открыт или .zip)
          created_at TEXT NOT NULL,
          updated_at TEXT NOT NULL,
          deleted_at TEXT,
          UNIQUE (archive_id, server_id)
        );

        -- СМЕНА ТЕКУЩЕГО АРХИВА (T-47-S0) — ПОРУЧЕНИЕ одного сервера другим, и потому
        -- ОТДЕЛЬНАЯ таблица, а не новый вид строки в archives (наука T-263): сервер прежней
        -- версии разобрал бы незнакомый вид через else-ветку и сделал НЕ ТО, а строку
        -- незнакомой таблицы приёмник журнала пропускает молча (ChangeLog.ApplyRow).
        --
        -- Смысл поручения: «архив <archive_id> становится текущим, а прежний текущий
        -- <prev_archive_id> — просто открытым». Исполняется оно НЕ в момент приезда строки,
        -- а в конце сеанса репликации — после того как прежний текущий архив ДОСЛАЛ свои
        -- данные в последний раз (ТЗ: сначала досылает, и только потом перестаёт быть текущим)
        CREATE TABLE IF NOT EXISTS archive_handovers (
          id              TEXT PRIMARY KEY,
          archive_id      TEXT NOT NULL REFERENCES archives(id),  -- новый текущий
          prev_archive_id TEXT NOT NULL DEFAULT '',               -- прежний текущий; пусто — первый архив
          created_at      TEXT NOT NULL,
          updated_at      TEXT NOT NULL,
          deleted_at      TEXT
        );

        -- ОТМЕТКИ ОБ ИСПОЛНЕНИИ смены текущего архива (T-47-S0) — НЕ реплицируются, как
        -- run_requests_applied и notification_marks: чужие отметки нам ничего не говорят.
        -- Отметка своя на КАЖДОГО партнёра: пока хоть один партнёр не получил последний
        -- досыл прежнего архива, поручение для него не исполнено
        CREATE TABLE IF NOT EXISTS archive_handovers_applied (
          handover_id TEXT NOT NULL,
          peer_id     TEXT NOT NULL,       -- партнёр, с которым досыл уже состоялся
          applied_at  TEXT NOT NULL,
          PRIMARY KEY (handover_id, peer_id)
        );

        -- ПРАВИЛА АРХИВАЦИИ (T-41-S0, выпуск 1.105) — что и какой давности пора уносить
        -- в архив. Таблица ОДНА на обе группы правил: у ОБЩЕГО правила организации (образец,
        -- с которого копируются правила нового архива) archive_id пуст, у правила архива —
        -- заполнен. Отдельной колонки-признака нет намеренно: признак производный, а колонка
        -- рядом со ссылкой разъехалась бы молча (наука T-11-S0 про общий опыт организации).
        --
        -- Реплицируется вместе с реестром архивов: правила принадлежат организации, а не
        -- машине — в отличие от archive_states, где лежит «открыт здесь или закрыт».
        --
        -- Состояния ПОТОМКОВ лежат строкой через запятую, а не отдельной таблицей связей:
        -- это не ссылки на записи (коды состояний — справочник, и кастомный код может
        -- исчезнуть), а условие правила, и оно должно уезжать партнёру одной строкой
        CREATE TABLE IF NOT EXISTS archive_rules (
          id             TEXT PRIMARY KEY,
          display_id     TEXT NOT NULL DEFAULT '',        -- ARR-N
          archive_id     TEXT REFERENCES archives(id),    -- пусто — ОБЩЕЕ правило организации
          target         TEXT NOT NULL DEFAULT 'tasks',   -- ArchiveRuleTargets: относится к
          task_status    TEXT NOT NULL DEFAULT '',        -- состояние задачи (только у задач)
          child_statuses TEXT NOT NULL DEFAULT '',        -- состояния потомков; пусто — любое
          activity       TEXT NOT NULL DEFAULT 'any',     -- активность остальных данных
          date_field     TEXT NOT NULL DEFAULT 'updated', -- по какой дате считать возраст
          age_kind       TEXT NOT NULL DEFAULT 'days',    -- срок временной или календарный
          age_days       INTEGER NOT NULL DEFAULT 0,      -- дней (временной срок)
          age_months     INTEGER NOT NULL DEFAULT 0,      -- месяцев (календарный срок)
          age_years      INTEGER NOT NULL DEFAULT 0,      -- лет (календарный срок)
          is_active      INTEGER NOT NULL DEFAULT 1,
          created_at     TEXT NOT NULL,
          updated_at     TEXT NOT NULL,
          deleted_at     TEXT
        );

        -- ПЛАГИНЫ (T-111-S0): шлюз в видеоредактор, конвертор, подключение к серверу MCP.
        -- Запись УРОВНЯ ОРГАНИЗАЦИИ и реплицируется: объект проекта здесь не годится — он
        -- живёт в одном проекте, а шлюз в Shotcut нужен всем проектам организации сразу.
        --
        -- ЧЕГО В ТАБЛИЦЕ НЕТ И ПОЧЕМУ: ни пути к программе, ни колонки «инициализировал
        -- сервер такой-то». Установка плагина всегда локальная (по образцу локальной
        -- модели), а реплицированный чужой путь ломает установку у соседа и «уже не
        -- уходит» (наука T-164). Всё пер-серверное — в config.json, раздел plugins;
        -- секреты подключения MCP — в secrets/*.json, как пароль почты.
        --
        -- Настройки записи лежат свободным JSON: их состав объявляет манифест
        -- plugins/<код>/plugin.json, и колонка на каждое поле означала бы миграцию схемы
        -- на каждый новый плагин (та же причина, что у профайлов моделей, T-13-S1)
        CREATE TABLE IF NOT EXISTS plugins (
          id               TEXT PRIMARY KEY,
          display_id       TEXT NOT NULL DEFAULT '',          -- PLG-N
          code             TEXT NOT NULL,                     -- editor.shotcut
          kind             TEXT NOT NULL DEFAULT 'gateway',   -- PluginKinds: gateway / mcp
          name             TEXT NOT NULL DEFAULT '',
          manifest_version INTEGER NOT NULL DEFAULT 1,        -- версия манифеста записи
          state            TEXT NOT NULL DEFAULT 'declared',  -- PluginStates
          settings_json    TEXT NOT NULL DEFAULT '{}',
          created_at       TEXT NOT NULL,
          updated_at       TEXT NOT NULL,
          deleted_at       TEXT
        );

        -- код плагина уникален в организации: по нему живут каталог манифеста и раздел
        -- config.json. Индекс частичный — удалённая запись не мешает завести плагин заново
        CREATE UNIQUE INDEX IF NOT EXISTS ux_plugins_code
          ON plugins(code) WHERE deleted_at IS NULL;

        CREATE TABLE IF NOT EXISTS events (
          id           TEXT PRIMARY KEY,
          node_id      TEXT NOT NULL,
          seq          INTEGER NOT NULL,
          ts           TEXT NOT NULL,
          actor_id     TEXT,
          project_id   TEXT,
          task_id      TEXT,
          event_type   TEXT NOT NULL,
          entity_type  TEXT,
          entity_id    TEXT,
          payload_json TEXT NOT NULL DEFAULT '{}',
          UNIQUE (node_id, seq)
        );

        """;

