using Microsoft.Data.Sqlite;

namespace AI2P.Storage;

/// <summary>
/// Вид базы данных (ТЗ п. 6.4.1, этап 40). Их две, и они не пересекаются по составу таблиц.
/// </summary>
public enum DatabaseKind
{
    /// <summary>БД организации: проекты, задачи, шаблоны, команды, исполнители, справочники,
    /// журнал работ. Своя на каждую организацию — отсюда своя нумерация и свои счётчики.</summary>
    Org,

    /// <summary>Серверная БД (<c>server.db</c>): аккаунты, организации, серверы организаций,
    /// идентификатор узла. Она одна на установку и живёт ВНЕ организаций.</summary>
    Server,
}

/// <summary>
/// БД SQLite: подключение, схема (ТЗ п. 6.4.2), идентификатор узла и счётчики display_id.
/// WAL-режим. Файл — <c>server.db</c> в dataDir (серверная) либо <c>ai2p.db</c> в каталоге
/// организации <c>data/orgs/&lt;ORG-N&gt;/</c> (организационная, ТЗ п. 2.15, этап 40).
/// </summary>
public sealed class Database
{
    private readonly string _connectionString;

    /// <summary>Корень хранилища — от него считаются все относительные пути. У организационной
    /// БД это каталог организации, у серверной — storage.dataDir.</summary>
    public string DataDir { get; }

    /// <summary>Вид БД: организация или сервер (ТЗ п. 6.4.1).</summary>
    public DatabaseKind Kind { get; }

    /// <summary>Идентификатор узла (компьютера) для event log — читается из meta при инициализации.</summary>
    public string NodeId { get; private set; } = "";

    public Database(string dataDir, string dbFile, DatabaseKind kind = DatabaseKind.Org)
    {
        Kind = kind;
        DataDir = Path.GetFullPath(dataDir);
        Directory.CreateDirectory(DataDir);
        ProtectDataDir(DataDir);
        _connectionString = new SqliteConnectionStringBuilder
        {
            DataSource = Path.Combine(DataDir, dbFile),
            // пул соединений выключен: встроенный пул Microsoft.Data.Sqlite при частых
            // параллельных Open/Dispose (UI + API + оркестратор) изредка отдаёт соединение
            // с уже освобождённым нативным хэндлом — "Cannot access a disposed object.
            // Object name: 'SQLitePCL.sqlite3'" (проявлялось при добавлении шаблона из
            // карточки проекта). БД локальная, WAL — открытие соединения дёшево.
            Pooling = false,
        }.ToString();
    }

    /// <summary>
    /// Права на каталог данных: только владелец (0700) — T-135. Сервер работает от обычного
    /// пользователя, а его домашний каталог на Linux обычно открыт на чтение всем (0755):
    /// без этого база организации (задачи, переписка, зашифрованные ключи API) читалась бы
    /// любым пользователем того же компьютера. Windows пропускается: там права задаёт ACL.
    /// </summary>
    private static void ProtectDataDir(string dir)
    {
        if (OperatingSystem.IsWindows())
        {
            return;
        }
        try
        {
            File.SetUnixFileMode(dir, UnixFileMode.UserRead | UnixFileMode.UserWrite
                                      | UnixFileMode.UserExecute);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException
                                      or PlatformNotSupportedException)
        {
            // файловая система без прав POSIX (сетевой диск, контейнер) — не повод не работать
        }
    }

    public SqliteConnection Open()
    {
        var conn = new SqliteConnection(_connectionString);
        conn.Open();
        using var cmd = conn.CreateCommand();
        // busy_timeout — из-за репликации (этап 43): применение пачки изменений держит
        // транзакцию записи целиком, и параллельная запись из UI не должна падать сразу
        cmd.CommandText = "PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON; PRAGMA busy_timeout=15000;";
        cmd.ExecuteNonQuery();
        return conn;
    }

    /// <summary>
    /// Создание схемы (идемпотентно) и чтение/генерация node_id.
    /// <paramref name="nodeId"/> — идентификатор узла серверной БД: узел один на компьютер,
    /// поэтому базы всех его организаций пишут события с ним же (ТЗ п. 6.4.3).
    /// </summary>
    public void Init(string? nodeId = null)
    {
        using var conn = Open();
        // триггеры журнала изменений (этап 43) снимаются на время миграций: они перечисляют
        // все колонки таблицы, а SQLite не даёт трогать колонку, на которую ссылается триггер.
        // В конце Init журнал ставится заново — уже по новому составу колонок
        ChangeLog.DropTriggers(conn);
        if (Kind == DatabaseKind.Server)
        {
            // таблицы, СМЕНИВШИЕ форму, пересоздаются до схемы: «CREATE TABLE IF NOT EXISTS»
            // старую форму не трогает, а миграция колонками эту разницу не выражает
            RebuildChangedTables(conn);
        }
        using (var cmd = conn.CreateCommand())
        {
            cmd.CommandText = Kind == DatabaseKind.Server ? ServerSchema : OrgSchema;
            cmd.ExecuteNonQuery();
        }
        if (Kind == DatabaseKind.Org)
        {
            MigrateOrg(conn);
        }
        else
        {
            MigrateServer(conn);
        }
        // ИНДЕКСЫ — ПОСЛЕ МИГРАЦИЙ, и это не мелочь оформления (todo92, версия 1.92).
        // Индекс ссылается на колонку, а колонку у УЖЕ СУЩЕСТВУЮЩЕЙ базы добавляет миграция:
        // пока индексы лежали в скрипте схемы, каждый новый индекс по новой колонке ронял
        // старт обновлённой установки насмерть — «no such column» на CREATE INDEX (так
        // падала версия 1.91 на ix_objects_parent, и войти в систему было нельзя).
        // На чистой базе порядок ничего не меняет: там колонки создаёт сама схема.
        // Оба списка идемпотентны (IF NOT EXISTS)
        using (var cmd = conn.CreateCommand())
        {
            cmd.CommandText = Kind == DatabaseKind.Server ? ServerIndexes : OrgIndexes;
            cmd.ExecuteNonQuery();
        }

        // ЛЕКСИЧЕСКИЙ ИНДЕКС ПО ОПЫТУ (T-268-S0) — после схемы и миграций, по той же причине,
        // что и индексы выше: он строится по колонке text таблицы experience. Таблица
        // производная и НЕ реплицируется (в ChangeLog.OrgTables её нет — это белый список);
        // FTS5 в сборке нет — установка молча работает без индекса, поиск деградирует
        // до подстрочного сравнения
        if (Kind == DatabaseKind.Org)
        {
            ExperienceIndex.Install(conn);
        }

        nodeId ??= Sql.Scalar<string>(conn, null, "SELECT value FROM meta WHERE key='node_id'")
                   ?? Guid.NewGuid().ToString();
        Sql.Exec(conn, null, "INSERT OR REPLACE INTO meta(key, value) VALUES ('node_id', @v)", ("@v", nodeId));
        NodeId = nodeId;

        // журнал изменений строк — основа репликации (ТЗ п. 6.1, этап 43). Ставится ПОСЛЕДНИМ:
        // триггеры пишутся по фактическому составу колонок, а его меняют миграции выше,
        // и первичное наполнение журнала подписывается уже известным node_id
        ChangeLog.Install(conn, Kind);
    }

    /// <summary>Значение из таблицы <c>meta</c>; null — ключа нет.</summary>
    public string? Meta(string key)
    {
        using var conn = Open();
        return Sql.Scalar<string>(conn, null, "SELECT value FROM meta WHERE key=@k", ("@k", key));
    }

    /// <summary>Записать значение в <c>meta</c>.</summary>
    public void SetMeta(string key, string value)
    {
        using var conn = Open();
        Sql.Exec(conn, null, "INSERT OR REPLACE INTO meta(key, value) VALUES (@k, @v)",
            ("@k", key), ("@v", value));
    }

    /// <summary>
    /// Согласовать идентификатор узла с внутренним ключом (unid) локального сервера
    /// (ТЗ гл. 6, этап 43). Узел и сервер — одно и то же: установка AI2P на компьютере.
    /// Одно значение вместо двух нужно репликации: автор изменения в журнале и сервер,
    /// которому это изменение не надо возвращать обратно, должны совпадать буквально.
    ///
    /// Меняется именно node_id, а не ключ сервера: на ключ сервера ссылаются связи
    /// с организациями и владение строками (<c>tasks.server_id</c>), а node_id — только
    /// авторство записей в журналах, где смена автора безобидна.
    /// </summary>
    public void AlignNodeId(string serverId)
    {
        if (serverId.Length == 0 || serverId == NodeId)
        {
            return;
        }
        SetMeta("node_id", serverId);
        NodeId = serverId;
    }

    /// <summary>
    /// Миграции схемы. v1 → v2 (ТЗ v1.10): признак «активен» у проектов/исполнителей/команд,
    /// плановая длительность у задач. v2 → v3 (ТЗ v1.13): справочник ИИ-моделей (таблица
    /// ai_models — в Schema через IF NOT EXISTS) и ссылка на модель у исполнителя.
    /// ALTER TABLE выполняется только для отсутствующих колонок,
    /// поэтому вызов идемпотентен и безопасен для свежих БД.
    /// </summary>
    private static void MigrateOrg(SqliteConnection conn)
    {
        EnsureColumn(conn, "projects", "is_active", "INTEGER NOT NULL DEFAULT 1");
        EnsureColumn(conn, "executors", "is_active", "INTEGER NOT NULL DEFAULT 1");
        EnsureColumn(conn, "teams", "is_active", "INTEGER NOT NULL DEFAULT 1");
        EnsureColumn(conn, "tasks", "planned_hours", "REAL");
        EnsureColumn(conn, "executors", "model_id", "TEXT");
        // v3 → v4 (ТЗ v1.15, биллинг): токены и валюта у задания (гл. 6.2, todo18)
        EnsureColumn(conn, "jobs", "input_tokens", "INTEGER NOT NULL DEFAULT 0");
        EnsureColumn(conn, "jobs", "output_tokens", "INTEGER NOT NULL DEFAULT 0");
        EnsureColumn(conn, "jobs", "currency", "TEXT NOT NULL DEFAULT ''");
        // v4 → v5 (ТЗ v1.17, todo20): иерархия команды, вопросы агентов в чате,
        // признак «кастом» у skills (таблица io_formats — в Schema через IF NOT EXISTS)
        EnsureColumn(conn, "team_members", "parent_executor_id", "TEXT");
        EnsureColumn(conn, "team_members", "is_lead", "INTEGER NOT NULL DEFAULT 0");
        EnsureColumn(conn, "chat_messages", "kind", "TEXT NOT NULL DEFAULT 'message'");
        EnsureColumn(conn, "chat_messages", "options_json", "TEXT NOT NULL DEFAULT '[]'");
        EnsureColumn(conn, "chat_messages", "answer_to_id", "TEXT");
        EnsureColumn(conn, "chat_messages", "job_id", "TEXT");
        EnsureColumn(conn, "chat_messages", "answered_at", "TEXT");
        EnsureColumn(conn, "skills", "is_custom", "INTEGER NOT NULL DEFAULT 1");
        // v5 → v6 (ТЗ v1.21, todo24): справочник действий агентов — иерархический код,
        // имя инструмента, признак «кастом»; тексты (заголовок/подсказка/промпт) по языкам —
        // таблица action_texts (в Schema через IF NOT EXISTS)
        EnsureColumn(conn, "actions", "code", "TEXT NOT NULL DEFAULT ''");
        EnsureColumn(conn, "actions", "tool_name", "TEXT");
        EnsureColumn(conn, "actions", "is_custom", "INTEGER NOT NULL DEFAULT 1");
        EnsureColumn(conn, "actions", "seed_version", "INTEGER NOT NULL DEFAULT 0");
        EnsureColumn(conn, "actions", "deleted_at", "TEXT");
        // v6 → v7 (ТЗ v1.22, todo25): правила безопасности (гл. 12) — мягкое удаление
        EnsureColumn(conn, "security_rules", "deleted_at", "TEXT");
        // v7 → v8 (ТЗ v1.26, todo28): числовой приоритет задачи (низкий 0–10, обычный 11–20,
        // высокий от 21) и признак «не разбивать на подзадачи»; существующим задачам числовой
        // приоритет проставляется из уровня (5/15/25) один раз — при добавлении колонки
        var priorityNumAdded = EnsureColumn(conn, "tasks", "priority_num", "INTEGER NOT NULL DEFAULT 15");
        if (priorityNumAdded)
        {
            Sql.Exec(conn, null,
                "UPDATE tasks SET priority_num = CASE priority WHEN 0 THEN 5 WHEN 1 THEN 15 ELSE 25 END");
        }
        EnsureColumn(conn, "tasks", "is_not_split", "INTEGER NOT NULL DEFAULT 0");
        // v8 → v9 (ТЗ v1.28, todo30): импорт задач из внешних систем — внешний id задачи
        // (защита от дублей при повторном импорте); справочник импортов — таблица в Schema
        EnsureColumn(conn, "tasks", "external_ref", "TEXT");
        // v9 → v10 (ТЗ п. 2.11, todo32): опыт по узлам шаблонов — таблица experience
        // переработана из незаполнявшейся заготовки этапа 1: на старых БД недостающие
        // колонки добавляются (старые колонки заготовки пусты и не мешают), на новых —
        // таблица создаётся сразу в новой форме (Schema)
        EnsureColumn(conn, "experience", "template_task_id", "TEXT");
        EnsureColumn(conn, "experience", "text", "TEXT NOT NULL DEFAULT ''");
        EnsureColumn(conn, "experience", "created_by", "TEXT");
        EnsureColumn(conn, "experience", "updated_by", "TEXT");
        EnsureColumn(conn, "experience", "deleted_at", "TEXT");
        // v10 → v11 (ТЗ п. 2.12, todo34): блокирующие задачи (task_blockers) и расписания
        // (schedules) — новые таблицы создаются самим Schema (CREATE IF NOT EXISTS)
        // v11 → v12 (ТЗ п. 2.12, todo34_2): проект расписания
        EnsureColumn(conn, "schedules", "project_id", "TEXT");
        // v12 → v13 (ТЗ v1.37, todo34_3): справочник состояний (task_statuses +
        // task_status_texts — новые таблицы в Schema через CREATE IF NOT EXISTS);
        // занятость исполнителя: «занят до» и % использования лимита провайдера
        EnsureColumn(conn, "executors", "busy_until", "TEXT");
        EnsureColumn(conn, "executors", "limit_percent", "REAL");
        // v13 → v14 (ТЗ v1.42, todo36_5): размещение модели — локальная или в облаке;
        // значение выводится из профайла подключения (AiModelService.SyncLocalFlags)
        // и проставляется всем записям при старте приложения
        EnsureColumn(conn, "ai_models", "is_local", "INTEGER NOT NULL DEFAULT 0");
        // v14 → v15 (ТЗ v1.46, todo39): у исполнителя-человека появляется ссылка на аккаунт
        // v15 → v16 (ТЗ v1.47, todo40): аккаунты переехали в СЕРВЕРНУЮ БД (они живут вне
        // организации), поэтому FK на accounts здесь больше нет — целостность на приложении
        EnsureColumn(conn, "executors", "account_id", "TEXT");
        // v17 → v18 (ТЗ v1.49, todo42): РАЗДЕЛЬНОЕ ВЛАДЕНИЕ — у строки ровно один сервер-писатель.
        // Внутренний ключ сервера-владельца (unid из серверной БД; FK через границу БД
        // невозможен — целостность на приложении). NULL — владельца нет, правит дирижёр.
        EnsureColumn(conn, "tasks", "server_id", "TEXT");
        EnsureColumn(conn, "schedules", "server_id", "TEXT");
        // ИИ с локальной моделью физически привязан к компьютеру (ТЗ гл. 6)
        EnsureColumn(conn, "executors", "server_id", "TEXT");
        // опыт накапливается везде, но правится только своим сервером
        EnsureColumn(conn, "experience", "server_id", "TEXT");
        // правила доступа к ФС зависят от сервера (пути на серверах разные, гл. 12)
        EnsureColumn(conn, "security_rules", "server_id", "TEXT");
        // локальная часть справочника моделей принадлежит серверу (ТЗ п. 2.9, гл. 6)
        EnsureColumn(conn, "ai_models", "server_id", "TEXT");
        // v18 → v19 (ТЗ v1.50, todo43): РЕПЛИКАЦИЯ. Новых колонок у сущностей организации
        // не появилось — журнал изменений (таблица changes) живёт отдельно и ставится
        // триггерами (ChangeLog), поэтому сами таблицы не тронуты.
        // v19 → v20 (ТЗ v1.51, todo44): репликация ФАЙЛОВ — в БД организации тоже без правок:
        // база сравнения и конфликты файлов лежат в серверной БД, они пер-серверные.
        // v20 → v21 (ТЗ v1.52, todo45): КЛЮЧИ API ОРГАНИЗАЦИИ — таблица model_keys создаётся
        // самой схемой (CREATE IF NOT EXISTS); значения в ней зашифрованы ключом организации
        // v21 → v22 (ТЗ п. 2.11, todo48): ОПЫТ НА УРОВНЕ ПРОЕКТА — у записи опыта появились
        // проект (вместо узла шаблона) и НАВЫК: опыт читает только исполнитель, у которого
        // этот навык есть. Обе колонки пустые у старых записей — они опыт узлов шаблонов
        EnsureColumn(conn, "experience", "project_id", "TEXT");
        EnsureColumn(conn, "experience", "skill_id", "TEXT");
        // v22 → v23 (T-121): ЛИМИТЫ АГЕНТОВ — у исполнителя лимит токенов за скользящее окно
        // и длина окна. Обе колонки пустые: пока лимиты не заданы, вычисление остатка
        // не делается вовсе (AgentLimitService)
        EnsureColumn(conn, "executors", "token_limit", "INTEGER");
        EnsureColumn(conn, "executors", "limit_window_hours", "REAL");
        // v23 → v24 (T-124): ТАЙМАУТ ОТВЕТА ИСПОЛНИТЕЛЯ — сколько ждать ответа модели.
        // Пусто у всех старых записей: это умолчание системы (30 мин, AgentTimeout), 0 —
        // ждать без ограничения (долгая генерация видео молчит десятки минут)
        EnsureColumn(conn, "executors", "response_timeout_minutes", "INTEGER");
        // v24 → v25 (T-129): АКТИВНОСТЬ УЧАСТНИКА В КОМАНДЕ — признак у записи состава, а не
        // у исполнителя: один и тот же исполнитель бывает активен в одной команде и выключен
        // в другой. Существующим участникам проставляется 1 (умолчание колонки) — поведение
        // старых команд не меняется
        EnsureColumn(conn, "team_members", "is_active", "INTEGER NOT NULL DEFAULT 1");
        // v25 → v26 (T-152): ОБСУЖДЕНИЕ ИЗ ВНЕШНЕЙ СИСТЕМЫ в чате задачи. Автор комментария
        // Trello исполнителем организации не является, а from_executor_id ссылается на
        // справочник исполнителей — поэтому имя автора хранится строкой («trello:<логин>»),
        // а внешний id сообщения защищает от дублей при повторном импорте карточки.
        // У своих сообщений обе колонки пусты — поведение чата не меняется
        EnsureColumn(conn, "chat_messages", "author_name", "TEXT NOT NULL DEFAULT ''");
        EnsureColumn(conn, "chat_messages", "external_ref", "TEXT");
        // v26 → v27 (T-191): НАЗВАНИЯ СПРАВОЧНИКОВ ПО ЯЗЫКАМ — role_texts, skill_texts,
        // io_format_texts (новые таблицы создаёт сама схема через CREATE IF NOT EXISTS).
        // Названия ролей, навыков и форматов больше не вписаны в код по-русски: встроенные
        // значения приезжают из файлов сида i18n/RefDataService_<lang>.json на КАЖДОМ языке
        // сразу (RefDataService.Seed), и старые записи получают тексты по совпадению кода —
        // ссылки задач и команд идут по id и не рвутся
        // v27 → v28 (T-185): ЧЕГО ЖДЁТ ЗАДАНИЕ. Состояние waiting_human означало одно — «агент
        // спросил человека»; теперь ждать можно ещё ответа агента ДРУГОЙ задачи и завершения
        // подзадач, на которые задача разошлась. Различать это состояниями нельзя: продолжение
        // у всех троих одинаковое (та же сессия агента), а вот смысл разный — задание, ждущее
        // подзадач, не занимает своего исполнителя (иначе подзадача, назначенная ему же,
        // не запустилась бы никогда) и не показывается человеку как вопрос. У старых заданий
        // колонка пуста — это «ждёт человека», прежнее поведение
        EnsureColumn(conn, "jobs", "wait_kind", "TEXT");
        // v28 → v29 (T-196): ЗАПУСК ЗАДАЧИ С ЧУЖОГО СЕРВЕРА. Обе таблицы создаёт сама схема
