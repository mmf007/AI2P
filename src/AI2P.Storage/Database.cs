    /// <summary>
    /// Миграция СЕРВЕРНОЙ БД v16 → v17 (ТЗ v1.48, todo41): сервер стал сущностью уровня
    /// установки (таблица <c>servers</c>), а <c>org_servers</c> — связью «многие ко многим»:
    /// один сервер обслуживает несколько организаций, организация живёт на нескольких серверах.
    /// Старая форма таблицы (сервер принадлежал одной организации, адрес хранился в ней же)
    /// распознаётся по колонке <c>url</c> и пересоздаётся: связи восстанавливает при старте
    /// сам реестр организаций — локальный сервер один и известен из config.json.
    ///
    /// Выполняется ДО скрипта схемы: он создаёт индекс по новой колонке <c>server_id</c>,
    /// которой в старой таблице нет.
    /// </summary>
    /// <summary>
    /// СНЯТЬ NOT NULL У <c>schedules.template_task_id</c> (T-46-S0, выпуск 1.105).
    /// У расписания-действия шаблона нет вовсе, а <c>ALTER TABLE</c> в SQLite обязательность
    /// колонки не снимает — таблица пересобирается целиком, и это единственный способ.
    ///
    /// Пересборка здесь безопасна ровно по двум причинам, и обе видны в <c>Init</c>:
    /// триггеры журнала изменений сняты на время миграций и ставятся заново В КОНЦЕ
    /// (по фактическому составу колонок), а индексы создаются ПОСЛЕ миграций и все
    /// с <c>IF NOT EXISTS</c>. На таблицу никто не ссылается внешним ключом, поэтому
    /// переименование новой на место старой ничего не ломает.
    ///
    /// Шаг идемпотентен: у уже пересобранной (и у чистой) базы обязательности нет, и
    /// пересборка не начинается вовсе.
    /// </summary>
