    /// <summary>Добавить колонку, если её нет; true — колонка добавлена этим вызовом
    /// (для одноразовых заполнений существующих строк при миграции).</summary>
    private static bool EnsureColumn(SqliteConnection conn, string table, string column, string ddl)
    {
        var exists = Sql.Query(conn, null, $"PRAGMA table_info({table})", r => r.S("name")).Contains(column);
        if (!exists)
        {
            Sql.Exec(conn, null, $"ALTER TABLE {table} ADD COLUMN {column} {ddl}");
        }
        return !exists;
    }

    /// <summary>
    /// Следующий display_id для префикса типа: T-17, PRJ-2, … (ТЗ п. 6.4.2), а в кластере —
    /// с суффиксом кода сервера: <c>T-18-S1</c> (ТЗ гл. 6 «Номера задач», этап 42).
    ///
    /// Номер — это ещё и имя каталога файлов задачи, и он вставлен в тексты описаний и чатов,
    /// поэтому переименование при слиянии недопустимо: два сервера без связи создали бы
    /// две разные <c>T-18</c>. Отсюда два следствия:
    /// <list type="bullet">
    /// <item>СЧЁТЧИК У КАЖДОГО СЕРВЕРА СВОЙ — строка счётчика называется <c>T@S1</c>, и
    /// каждый сервер пишет только свою: репликация счётчиков конфликтов не даёт;</item>
    /// <item>сервер не указан — суффикса нет: такие строки создаются только на дирижёре,
    /// а он один.</item>
    /// </list>
    /// Номер НЕ меняется при смене сервера у задачи — это идентификатор, а не признак владения.
    /// </summary>
    /// <param name="serverCode">Код сервера в организации (S0, S1, …); пусто — без суффикса.</param>
    public static string NextDisplayId(SqliteConnection conn, SqliteTransaction tx, string prefix,
        string serverCode = "")
    {
        serverCode = serverCode.Trim();
        var counter = serverCode.Length > 0 ? $"{prefix}@{serverCode}" : prefix;
        var next = Sql.Scalar<long?>(conn, tx, "SELECT next FROM counters WHERE prefix=@p", ("@p", counter)) ?? 1;
        Sql.Exec(conn, tx,
            "INSERT INTO counters(prefix, next) VALUES (@p, @n) ON CONFLICT(prefix) DO UPDATE SET next=@n",
            ("@p", counter), ("@n", next + 1));
        return serverCode.Length > 0 ? $"{prefix}-{next}-{serverCode}" : $"{prefix}-{next}";
    }

