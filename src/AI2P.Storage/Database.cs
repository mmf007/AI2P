        Sql.Exec(conn, null, """
            CREATE TABLE schedules_v43 (
              id               TEXT PRIMARY KEY,
              display_id       TEXT NOT NULL DEFAULT '',
              project_id       TEXT REFERENCES projects(id),
              template_task_id TEXT REFERENCES tasks(id),
              action           TEXT,
