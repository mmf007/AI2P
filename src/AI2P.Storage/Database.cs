          initiator_server_id TEXT NOT NULL DEFAULT '', -- кто подал: target либо from
          status              TEXT NOT NULL DEFAULT 'pending', -- ConductorRequestStatus
          note                TEXT NOT NULL DEFAULT '',
          requested_by        TEXT NOT NULL DEFAULT '', -- человек, подавший заявку
          decided_by          TEXT NOT NULL DEFAULT '', -- человек, принявший решение
          decided_at          TEXT,
          unilateral          INTEGER NOT NULL DEFAULT 0, -- принята в одностороннем порядке
          server_id           TEXT,                   -- сервер-АВТОР строки (он же инициатор)
          created_at          TEXT NOT NULL,
          updated_at          TEXT NOT NULL,
          deleted_at          TEXT
        );

