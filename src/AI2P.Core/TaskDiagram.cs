using AI2P.Core.Api;
using AI2P.Core.Entities;

namespace AI2P.Core;

/// <summary>
/// РАСКЛАДКА ДИАГРАММЫ ПОДЗАДАЧ ПО ВРЕМЕНИ (T-132-S0): каждой задаче считается момент начала
/// (в часах от начала диаграммы) так, как её будет выполнять запуск иерархии (T-159).
///
/// Правил ровно три, и все три взяты из настоящей очереди, а не выдуманы для картинки:
/// <list type="number">
/// <item>родитель начинается после ВСЕХ своих потомков — очередь идёт снизу вверх;</item>
/// <item>задача начинается после своих блокирующих (ТЗ v1.35), если те есть в этой же
/// иерархии; блокирующая снаружи временем не сдвигает — её срока мы не знаем;</item>
/// <item>один исполнитель делает одну задачу за раз — иначе на дорожке квадраты налезали бы
/// друг на друга, и диаграмма врала бы про параллельность работы.</item>
/// </list>
///
/// Порядок обхода — «готовые вперёд»: следующей кладётся ПЕРВАЯ по очереди задача, все
/// зависимости которой уже размещены. Кольцо зависимостей (испорченный parent_id, взаимные
/// блокирующие) не должно вешать отрисовку, поэтому когда готовых нет вовсе, кладётся первая
/// оставшаяся задача принудительно.
///
/// ЧЕТВЁРТОЕ ПРАВИЛО (T-164-S0): уже СЛУЧИВШЕЕСЯ раскладывается в том порядке, в каком оно
/// случилось на самом деле, а не по приоритету очереди. Порядок в списке — очередь иерархии
/// (внутри уровня по убыванию приоритета), и задача, которую очередь запустила бы первой,
/// занимала дорожку исполнителя с нуля, даже если по факту её начали ПОСЛЕДНЕЙ, а
/// предыдущие задачи того же исполнителя уже сделаны: на картинке она уезжала в самое
/// начало шкалы, левее собственных предшественников. Поэтому перед раскладкой список
/// пересортировывается по фактическому началу (<see cref="TaskDiagramNodeDto.StartedAt"/>),
/// а ещё не начатые задачи идут после начатых в прежнем порядке очереди.
///
/// ПЯТОЕ ПРАВИЛО (T-171-S0): задача, которую уже взяли в работу, идёт раньше тех, что ещё
/// ждут своей очереди, — но только среди РАВНЫХ ей по приоритету задач одного родителя.
/// Фактическое начало есть только у задачи с заданием (<c>jobs.started_at</c>), а «в работе»
/// бывает и без задания — так стоит задача человека и задача, которую в это состояние
/// перевели руками. Такие задачи различались только приоритетом, и при РАВНОМ приоритете у
/// одного исполнителя идущая задача рисовалась правее ждущих — там очередь и сама различает
/// их лишь временем создания, поэтому картинка спорила с тем, что человек видит в дереве.
///
/// ШЕСТОЕ ПРАВИЛО (T-192-S0) — оно же граница четвёртого: «уже случившееся» это ТОЛЬКО
/// СДАННАЯ задача (<see cref="TaskDiagramNodeDto.Settled"/> — проверка, готово, отмена).
/// Всё незаконченное (ждёт, идёт, на паузе, встало с ошибкой, в доработке) — это ПЛАН, и его
/// порядок задаёт очередь иерархии, то есть числовой приоритет с учётом иерархии. До этой
/// правки фактическое начало считалось у любой задачи с заданием, поэтому идущая (и даже
/// ждущая, но однажды запускавшаяся) задача занимала дорожку по времени своего задания и
/// обгоняла незаконченные задачи с БОЛЬШИМ приоритетом — жалоба заказчика по выпуску 1.124:
/// «не готовые и в работе задачи должны стоять у исполнителя ровно так, как их запустит
/// старт иерархии». Порядок очереди внутри плановой группы сохраняется целиком.
///
/// СЕДЬМОЕ ПРАВИЛО (T-192-S0, второй заход) — задачи кладутся ПО ОДНОЙ, а не пачками. Раньше
/// каждый проход клал СРАЗУ ВСЕ готовые задачи, то есть сначала все листья дерева, потом их
/// родителей, потом родителей родителей. Дорожку исполнителя при этом занимала не та задача,
/// до которой очередь дойдёт раньше, а та, что оказалась ближе к листьям: задача с
/// подзадачами ждала целый проход и уезжала правее задач с МЕНЬШИМ приоритетом, у которых
/// подзадач нет (жалоба: T-74-S0, приоритет 35, стояла правее T-145-S0 с приоритетом 15 —
/// обе ждут, обе у одного исполнителя, обе дети T-204). Настоящая очередь так не работает:
/// освободив исполнителя, она берёт ПЕРВУЮ по очереди задачу из тех, что уже можно взять,
/// то есть родитель встаёт сразу за своими подзадачами, а не за всеми листьями дерева.
/// </summary>
public static class TaskDiagram
{
    /// <summary>Считает <see cref="TaskDiagramNodeDto.StartHours"/> у всех узлов.
    /// Список приходит в порядке очереди иерархии и в нём же остаётся.
    ///
    /// <paramref name="minDuration"/> — НАИМЕНЬШАЯ длительность (часы), которой задача занимает
    /// место на диаграмме (T-306). Рисуется задача не уже некоторого числа пикселей (наименьшая
    /// ширина прямоугольника плюс зазор между соседями, T-159-S0), а вот следующая за ней задача
    /// до этой правки начиналась по НАСТОЯЩЕМУ времени — то есть двухминутную задачу её сосед по
    /// дорожке накрывал наполовину. Кто считает раскладку, тот и знает свой масштаб, поэтому
    /// величина приходит снаружи: на сервере она нулевая (масштаб выбирает клиент).</summary>
    public static void Layout(List<TaskDiagramNodeDto> nodes, double minDuration = 0)
    {
        var ids = nodes.Select(n => n.Id).ToHashSet(StringComparer.Ordinal);
        var byId = nodes.ToDictionary(n => n.Id, StringComparer.Ordinal);
        // ВОСЬМОЕ ПРАВИЛО (T-305-S0): «Условие» и «Цикл до» очередь запускает РАНЬШЕ своих
        // потомков (JobOrchestrator.RunIfNodeAsync/RunLoopNodeAsync), поэтому их потомки
        // ждут саму задачу, а не наоборот. Родитель такой задачи ждёт всё её поддерево —
        // иначе он встал бы сразу за условием, раньше выбранной ветки
        var deps = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        foreach (var n in nodes)
        {
            var list = new List<string>();
            if (!RunsFirst(n))
            {
                foreach (var c in nodes.Where(c => c.ParentId == n.Id))
                {
                    list.Add(c.Id);
                    if (RunsFirst(c))
                    {
                        list.AddRange(Descendants(nodes, c.Id));
                    }
                }
            }
            if (n.ParentId is { } p && byId.TryGetValue(p, out var parent) && RunsFirst(parent))
            {
                list.Add(p);
            }
            list.AddRange(n.BlockerIds.Where(ids.Contains));
            deps[n.Id] = list.Distinct(StringComparer.Ordinal).ToList();
        }

        var finish = new Dictionary<string, double>(StringComparer.Ordinal);
        var laneFree = new Dictionary<string, double>(StringComparer.Ordinal);
        var rest = Ordered(nodes);
        while (rest.Count > 0)
        {
            // ПО ОДНОЙ ЗАДАЧЕ ЗА РАЗ (T-192-S0): следующей идёт первая по очереди задача, чьи
            // зависимости уже размещены. Пачка «все готовые сразу» ставила родителя после ВСЕХ
            // листьев дерева, а не сразу за своими подзадачами
            var index = rest.FindIndex(n => deps[n.Id].All(finish.ContainsKey));
            if (index < 0)
            {
                index = 0; // кольцо зависимостей: кладём как есть, лишь бы не зациклиться
            }
            var node = rest[index];
            rest.RemoveAt(index);

            var start = 0.0;
            foreach (var dep in deps[node.Id])
            {
                if (finish.TryGetValue(dep, out var done))
                {
                    start = Math.Max(start, done);
                }
            }
            // дорожка исполнителя занята предыдущей его задачей; у задачи без
            // исполнителя дорожки нет — такие не сериализуются между собой
            if (node.ExecutorId.Length > 0 && laneFree.TryGetValue(node.ExecutorId, out var busy))
            {
                start = Math.Max(start, busy);
            }
            node.StartHours = start;
            // место, которое задача занимает на картинке, не меньше minDuration: иначе
            // следующая задача начиналась бы внутри нарисованного квадрата (T-306)
            var end = start + Math.Max(Math.Max(node.DurationHours, 0.0), minDuration);
            finish[node.Id] = end;
            if (node.ExecutorId.Length > 0)
            {
                laneFree[node.ExecutorId] = end;
            }
        }
    }

    /// <summary>Задача запускается РАНЬШЕ своих потомков (T-305-S0): «Условие» и «Цикл до».
    /// «Цикл после» идёт как обычная задача — его анализатор ждёт потомков.</summary>
    public static bool RunsFirst(TaskDiagramNodeDto node) =>
        TaskFlow.Normalize(node.Flow.Type) is TaskFlow.If or TaskFlow.Loop;

    /// <summary>Все потомки задачи внутри набора узлов; кольцо в данных не вешает обход.</summary>
    private static List<string> Descendants(List<TaskDiagramNodeDto> nodes, string id)
    {
        var found = new List<string>();
        var seen = new HashSet<string>(StringComparer.Ordinal) { id };
        var queue = new Queue<string>();
        queue.Enqueue(id);
        while (queue.Count > 0)
        {
            var at = queue.Dequeue();
            foreach (var child in nodes.Where(c => c.ParentId == at && seen.Add(c.Id)))
            {
                found.Add(child.Id);
                queue.Enqueue(child.Id);
            }
        }
        return found;
    }

    /// <summary>
    /// Порядок, в котором задачи занимают дорожки исполнителей.
    ///
    /// Сначала ФАКТ — сданные задачи в том порядке, в каком их на самом деле начинали
    /// (T-164-S0); у сданной задачи без задания фактического начала нет, такие идут в конце
    /// своей группы в порядке очереди. Потом ПЛАН — всё незаконченное в порядке очереди
    /// иерархии, то есть по числовому приоритету с учётом иерархии (T-192-S0).
    ///
    /// Единственная перестановка внутри плана — правило T-171-S0: взятая в работу задача
    /// обгоняет ждущую. Действует оно только среди РАВНЫХ по приоритету задач одного
    /// родителя (там очередь различает их лишь временем создания), поэтому переставляются
    /// задачи в своих же местах списка, а порядок приоритетов остаётся нетронутым.
    /// </summary>
    private static List<TaskDiagramNodeDto> Ordered(List<TaskDiagramNodeDto> nodes)
    {
        var fact = nodes.Where(n => n.Settled).OrderBy(n => n.StartedAt ?? DateTime.MaxValue);
        var plan = nodes.Where(n => !n.Settled).ToList();
        foreach (var group in plan
                     .Select((node, index) => (Node: node, Index: index))
                     .GroupBy(x => (Parent: x.Node.ParentId ?? "", x.Node.PriorityNum)))
        {
            var slots = group.Select(x => x.Index).ToList();
            if (slots.Count < 2)
            {
                continue;
            }
            // GroupBy и OrderBy устойчивы: у равных по «взята в работу» порядок прежний
            var sorted = group.Select(x => x.Node).OrderBy(n => Taken(n) ? 0 : 1).ToList();
            for (var i = 0; i < slots.Count; i++)
            {
                plan[slots[i]] = sorted[i];
            }
        }
        return fact.Concat(plan).ToList();
    }

    /// <summary>Задачу уже ВЗЯЛИ в работу (T-171-S0): она идёт раньше тех, что ещё ждут
    /// очереди. «Пауза» сюда же — это начатая и не законченная работа (агент ждёт ответа),
    /// а не ожидание очереди. Живое задание учитывается отдельно от статуса: задачу могли
    /// запустить, а статус ещё не переписать.</summary>
    private static bool Taken(TaskDiagramNodeDto node) =>
        node.Status is TaskStatuses.InProgress or TaskStatuses.Paused
        || node.WorkStatus.Length > 0
        || node.HasActiveJob;
}
