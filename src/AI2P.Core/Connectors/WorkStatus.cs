namespace AI2P.Core.Connectors;

/// <summary>
/// Статус работы члена команды (ТЗ v1.14, «Запуск работы команды») — вычисляемое значение:
/// для ИИ — не подключен / в процессе подключения / подключен / ошибки подключения;
/// для человека — офлайн / онлайн; для любого вида — «не активен» (todo_bugfix_3):
/// исполнитель выключен в справочнике после включения в команду — не подключается
/// и задачи с ним не запускаются.
/// </summary>
public enum ExecutorWorkState
{
    // ИИ
    NotConnected,
    Connecting,
    Connected,
    Error,
    // человек
    Offline,
    Online,
    // любой вид: исполнитель выключен в справочнике (ТЗ п. 2.2)
    Inactive,
}
