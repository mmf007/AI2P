namespace AI2P.Core;

/// <summary>
/// ИНСТРУМЕНТ СЕРВЕРА MCP, каким его объявил сам сервер ответом на <c>tools/list</c>
/// (T-119-S0). Руками этот список НЕ пишется нигде — ни в манифесте плагина, ни в базе:
/// он снимается с сервера при инициализации и при явном обновлении, а между ними живёт
/// в кэше ЭТОГО сервера (раздел <c>plugins</c> файла config.json).
///
/// ПОЧЕМУ НЕ В БАЗЕ ОРГАНИЗАЦИИ: подключение к серверу MCP пер-серверное — программу на
/// транспорте <c>stdio</c> запускает тот компьютер, где она стоит, — и список её
/// инструментов у соседа может быть другим (другая версия сервера, другой набор пакетов).
/// Реплицируется же не список, а его СЛЕДСТВИЕ: записи справочника действий, которые
/// заводит инициализация. Колонки <c>objects.tools_cache_json</c> и соседние остаются
/// в таблице неиспользованными — вид объекта <c>mcp</c> снят решением заказчика (T-111-S0).
/// </summary>
/// <param name="Name">Имя инструмента, которым его зовёт агент: <c>unity_run_tests</c>.</param>
/// <param name="Title">Человеческое название; пусто — сервер его не назвал, и в справочнике
/// действий вместо него встанет само имя инструмента.</param>
/// <param name="Description">Подсказка из описания инструмента — она ложится в подсказку
/// записи справочника действий и уезжает агенту описанием инструмента.</param>
public sealed record McpToolInfo(string Name, string Title = "", string Description = "")
{
    /// <summary>Название для записи справочника: своё, если сервер его назвал, иначе имя.</summary>
    public string TitleOrName => Title.Trim().Length > 0 ? Title.Trim() : Name;
}
