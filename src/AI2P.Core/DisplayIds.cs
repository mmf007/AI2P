namespace AI2P.Core;

/// <summary>
/// НОМЕР ЗАПИСИ (display_id) — правило порядка, общее на всю систему (T-248).
///
/// Номер строится счётчиком типа: <c>T-17</c>, <c>PRJ-2</c>, а в кластере — с суффиксом кода
/// сервера: <c>T-18-S1</c> (ТЗ гл. 6 «Номера задач»). Сортировать такие номера как СТРОКИ
/// нельзя: <c>T-10</c> оказалось бы раньше <c>T-2</c>, а человек читает номер как число.
///
/// До T-248 один и тот же разбор был написан в четырёх представлениях подряд
/// (таблица задач, исполнители, расписания, «в работе у ИИ») плюс требовался пятый — списку
/// блокирующих задач в форме задачи. Правило порядка живёт здесь, как <see cref="TaskTags"/>:
/// им пользуются все слои, а разойтись молча ему больше негде.
/// </summary>
public static class DisplayIds
{
    /// <summary>
    /// Числовой порядок номера: <c>T-2</c> раньше <c>T-10</c>, суффикс кода сервера
    /// (<c>T-18-S1</c>) на порядок не влияет — сортируем по СЧЁТЧИКУ, то есть по части
    /// между первым и вторым дефисом. Номер без числа (пустой у только что созданной
    /// записи, чужой формат) уходит в конец списка.
    /// </summary>
    public static long Order(string? displayId)
    {
        if (displayId is null)
        {
            return long.MaxValue;
        }
        var start = displayId.IndexOf('-');
        if (start < 0)
        {
            return long.MaxValue;
        }
        var rest = displayId[(start + 1)..];
        var end = rest.IndexOf('-');
        var number = end >= 0 ? rest[..end] : rest;
        return long.TryParse(number, out var n) ? n : long.MaxValue;
    }
}
