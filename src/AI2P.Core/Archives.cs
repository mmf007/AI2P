namespace AI2P.Core;

/// <summary>
/// АРХИВАЦИЯ (T-40-S0, выпуск 1.105) — коды и правила именования, общие на все слои.
///
/// Назначение архивации — уменьшить оперативный объём задач и всего, что с ними связано.
/// Архивация это ПЕРЕНОС данных из рабочей среды в архивную; ведётся по каждой организации
/// отдельно. Данные в архиве изменению не подлежат: их можно только посмотреть или
/// скопировать обратно в рабочую среду.
///
/// Все архивы организации лежат в её подкаталоге <c>arc</c>: открытый — каталогом
/// <c>arc/&lt;код&gt;/</c> (внутри своя база SQLite ТОЙ ЖЕ схемы, что у организации, и
/// подкаталог файлов проектов — то есть каталог архива устроен как каталог организации,
/// и готовые сервисы чтения работают с ним как есть), закрытый — одним файлом
/// <c>arc/&lt;код&gt;.zip</c>.
/// </summary>
public static class Archives
{
    /// <summary>Подкаталог организации, в котором лежат все её архивы.</summary>
    public const string Dir = "arc";

    /// <summary>Имя файла базы внутри открытого архива — то же, что у организации.</summary>
    public const string DbFile = "ai2p.db";

    /// <summary>Подкаталог файлов проектов внутри архива — то же имя, что в каталоге
    /// организации (<c>FileStore</c>): пути в архивной базе тогда совпадают с рабочими.</summary>
    public const string ProjectsDir = "projects";

    /// <summary>Расширение закрытого архива.</summary>
    public const string ZipExt = ".zip";

    /// <summary>
    /// Код архива годится как имя каталога и файла: латиница, цифры, дефис и подчёркивание,
    /// от 1 до 64 знаков. Кириллицу и пробелы не берём намеренно — код едет репликацией
    /// на серверы с другими файловыми системами и кодировками, а имя для человека лежит
    /// отдельным полем.
    /// </summary>
    public static bool IsValidCode(string? code)
    {
        if (code is null || code.Length is 0 or > 64)
        {
            return false;
        }
        foreach (var ch in code)
        {
            if (!(char.IsAsciiLetterOrDigit(ch) || ch is '-' or '_'))
            {
                return false;
            }
        }
        return true;
    }
}

/// <summary>
/// СОСТОЯНИЕ АРХИВА НА КОНКРЕТНОМ СЕРВЕРЕ (T-40-S0). Не путать с признаком «текущий»:
/// «текущий» — свойство САМОГО архива, оно одно на всю организацию и реплицируется,
/// а открыт/закрыт/удалён — свойство архива на ЭТОЙ машине, и оно не реплицируется никогда.
/// </summary>
public static class ArchiveStates
{
    /// <summary>Лежит на этом компьютере распакованным (каталогом) — на него можно
    /// переключиться для просмотра.</summary>
    public const string Open = "open";

    /// <summary>Лежит на этом компьютере одним файлом .zip — переключиться нельзя.</summary>
    public const string Closed = "closed";

    /// <summary>Удалён с этого сервера (или сюда никогда не приезжал). Запись реестра при
    /// этом остаётся: архив есть на других серверах, и его можно скачать (T-47-S0).</summary>
    public const string Deleted = "deleted";

    public static readonly string[] All = [Open, Closed, Deleted];
}

/// <summary>
/// СПОСОБ ПЕРЕНОСА ПРАВИЛ АРХИВАЦИИ в новый архив (T-40-S0; сами правила — T-41-S0).
/// Ядро архивации только принимает выбор человека и хранит его строкой у архива:
/// что с ним делать, решает задача правил.
/// </summary>
public static class ArchiveRuleModes
{
    /// <summary>Взять общие правила архивации организации (умолчание).</summary>
    public const string Common = "common";

    /// <summary>Скопировать правила предыдущего текущего архива.</summary>
    public const string Copy = "copy";

    /// <summary>Без правил — человек задаст их сам.</summary>
    public const string Empty = "empty";

    public static readonly string[] All = [Common, Copy, Empty];
}
