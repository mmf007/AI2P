namespace AI2P.Core;

/// <summary>Общие сведения о приложении.</summary>
public static class AppInfo
{
    public const string Name = "AI2P";

    /// <summary>
    /// НОМЕР БИЛДА (ТЗ гл. 4.3, этап 46) — номер <c>NN</c> из строки «Для версии: 1.NN»
    /// рабочего задания (задания ставятся задачами в приложении). По нему сравниваются версии
    /// при обновлении: скрипт установки кладёт новую выкладку поверх старой, только если билд
    /// вырос, а приложение при первом старте после обновления доводит данные до нового билда
    /// (<see cref="Version"/>, <c>Upgrade</c>).
    ///
    /// ПРАВИЛО: номер меняется с КАЖДЫМ заданием, где указана новая версия. Здесь и в
    /// <see cref="Version"/> — единственные два места, где он задаётся; их согласованность
    /// проверяется тестом. Порядок работ с новым заданием — <c>doc/AI2P_release.md</c>.
    /// </summary>
    public const int Build = 150;

    /// <summary>
    /// Версия приложения в формате <c>1.&lt;номер билда&gt;</c> (ТЗ гл. 4.3): показывается
    /// в настройках, пишется в <c>version.json</c> выкладки, по ней сравниваются версии при
    /// обновлении. Начиная с 1.60 (T-117) версия приложения и версия ТЗ
    /// (<c>doc/AI2P_ТЗ_vX.Y.md</c>) ОДИНАКОВЫ: с каждой новой версией выпускается ТЗ
    /// с тем же номером.
    /// </summary>
    public const string Version = "1.150";

    /// <summary>
    /// Номер билда из строки версии вида <c>1.46</c>; 0 — разобрать не удалось. Нужна
    /// приложению (сравнение с записанным в базе билдом) и скрипту установки.
    /// </summary>
    public static int BuildOf(string? version)
    {
        var parts = (version ?? "").Trim().Split('.');
        return parts.Length >= 2 && int.TryParse(parts[1], out var build) ? build : 0;
    }

    /// <summary>
    /// Debug-режим работы (сборка Debug). В нём разрешено менять признак isCustom
    /// у моделей справочника (ТЗ п. 2.9); в релизе добавляемые модели — всегда кастомные.
    /// </summary>
    public static bool IsDebug =>
#if DEBUG
        true;
#else
        false;
#endif
}
