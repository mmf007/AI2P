    /// </summary>
    public bool SiblingsInPrompt { get; set; }
    /// <summary>
    /// ВРЕМЯ ↔ КАЧЕСТВО (T-23-S0): 0.0 — минимум времени и минимум качества, 1.0 — максимум
    /// качества и максимум времени. Значение печатается в промпт задания, а как именно на
    /// него отзываться (какие проверки гонять, насколько подробно разбираться) — записано в
