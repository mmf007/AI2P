/// <summary>
/// КТО ВПРАВЕ ПОДАТЬ ЗАЯВКУ НА СМЕНУ ДИРИЖЁРА (T-21-S1).
///
/// Правило живёт здесь, а не в обработчике HTTP, по той же причине, что и <see cref="Ownership"/>:
/// его спрашивают ДВОЕ — кнопка в форме сервера и эндпойнт, который эту кнопку обслуживает.
/// Разъедься они, и кнопка окажется живой там, где действие запрещено: человек заполнит
/// форму и получит отказ.
/// </summary>
public static class ConductorRules
{
    /// <summary>
    /// Почему заявку «назначить дирижёром этот сервер» подать нельзя; null — можно.
    /// </summary>
    /// <param name="target">Сервер, которого назначают дирижёром.</param>
    /// <param name="link">Его связь с организацией; null — он к ней не подключён.</param>
    /// <param name="localServerId">Сервер, НА КОТОРОМ нажимают кнопку.</param>
    /// <param name="conductorServerId">Сегодняшний дирижёр организации; пусто — его нет.</param>
    public static string? ProblemWithRequest(ServerNode target, OrgServer? link,
        string localServerId, string conductorServerId)
    {
        if (link is not { Status: OrgServerStatus.Active })
        {
            return Loc.T("msg.conductor.6", Name(target));
        }
        if (link.IsConductor)
        {
            return Loc.T("msg.conductor.7", Name(target));
        }
        // ПЕТЛЕВОЙ АДРЕС (ТЗ гл. 6, T-141): «localhost» и «127.0.0.1» у каждого компьютера
        // означают его самого. Дирижёра зовут ВСЕ остальные серверы кластера, и по такому
        // адресу они попадут к себе — дирижёром такой сервер быть не может
        if (ServerAddress.IsLoopback(target.Hostname))
        {
            return Loc.T("msg.conductor.8", target.Hostname);
        }
        // ТОЛЬКО ДВЕ СТОРОНЫ: назначаемый сервер и сегодняшний дирижёр. Третий сервер
        // кластера в чужую передачу не вмешивается — он не знает ни готовности назначаемого,
        // ни причин, по которым дирижёр отдаёт дирижёрство
        if (localServerId != target.Id && localServerId != conductorServerId)
        {
            return Loc.T("msg.conductor.9");
        }
        return null;
    }

    private static string Name(ServerNode server) =>
        server.Name.Length > 0 ? server.Name : server.Hostname;
}

