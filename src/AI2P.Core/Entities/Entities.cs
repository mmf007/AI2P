    /// <para>null — «не задано»: тогда берётся умолчание ПРОЕКТА
    /// (<see cref="ProjectSettings.TimeQuality"/>, у него своё умолчание 0.5). Пустое значение
    /// и ноль — разные вещи, поэтому поле именно nullable: 0.0 это осмысленный выбор «гнать
    /// как можно быстрее». Форма новой задачи подставляет сюда умолчание проекта, а задачи,
    /// заведённые мимо формы (подзадача агента, импорт, авторазбиение), оставляют поле
