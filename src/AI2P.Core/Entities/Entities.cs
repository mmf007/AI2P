/// <summary>
/// Задача, бизнес-процесс или шаблон — одна таблица tasks (ТЗ пп. 2.1, 2.3, 6.4.2).
/// </summary>
public sealed class TaskItem : Entity
{
    public string? ProjectId { get; set; }
    public string? TeamId { get; set; }
    /// <summary>Родительский бизнес-процесс или родительская задача.</summary>
