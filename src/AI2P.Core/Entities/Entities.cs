    /// состояние архива не «удалён». Список нужен экрану: у удалённого здесь архива надо
    /// показать, откуда его можно скачать (T-47-S0). В таблице реестра не хранится —
    /// собирается при выдаче из РЕПЛИЦИРУЕМОЙ таблицы <c>archive_servers</c> (T-47-S0):
    /// своё наличие каждый сервер объявляет сам, и только так соседи узнают, где архив есть.
    /// </summary>
    public List<string> Servers { get; set; } = [];
}

