/// <summary>
/// Пути в паттернах правил доступа к каталогам (ТЗ гл. 12, todo25). Понятие «полный путь»
/// НЕ зависит от ОС приложения (в отличие от Path.IsPathRooted): полным считается путь
/// Windows-вида (буква диска: X:\… или X:/…), unix-вида (/…), UNC (\\сервер\…).
/// Частая ошибка ввода: буква диска набрана кириллицей («с:» вместо «c:» — одна клавиша);
/// такой паттерн никогда не совпадёт с реальным путём — ловится отдельной проверкой.
/// </summary>
public static class SecurityRulePaths
{
    /// <summary>Полный путь независимо от ОС: X:\… / X:/… (Windows), /… (unix), \\… (UNC),
    /// а также «~/…» — путь от домашнего каталога пользователя (T-135): на Linux/macOS
    /// каталоги задают именно так, и правило «~/ai/AI2P/data» обязано считаться полным,
    /// а не путём внутри папки проекта.</summary>
    public static bool IsFullPath(string pattern)
    {
        pattern = pattern.Trim();
        if (pattern.Length == 0)
        {
            return false;
        }
        if (pattern[0] is '/' or '\\')
        {
            return true; // unix-корень или UNC
        }
        if (PathHome.StartsWithHome(pattern))
        {
            return true; // ~/… — домашний каталог этого пользователя
        }
        return pattern.Length >= 3
               && pattern[0] is (>= 'A' and <= 'Z') or (>= 'a' and <= 'z')
               && pattern[1] == ':'
               && pattern[2] is '\\' or '/';
    }

    /// <summary>Буква диска набрана кириллицей («с:\tmp» вместо «c:\tmp») — частая ошибка
    /// раскладки; для понятного сообщения об ошибке вместо «нужен полный путь».</summary>
    public static bool HasCyrillicDriveLetter(string pattern)
    {
        pattern = pattern.Trim();
        return pattern.Length >= 2
               && pattern[1] == ':'
               && pattern[0] is (>= 'а' and <= 'я') or (>= 'А' and <= 'Я') or 'ё' or 'Ё';
    }
}

