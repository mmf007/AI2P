    /// <summary>Запуск всей иерархии задачи (кнопка «запустить иерархию», T-159).</summary>
    public const string Hierarchy = "hierarchy";

    /// <summary>Остановить активное задание задачи (кнопка «остановить», T-263): та же
    /// заявка, что и у запуска, — задание снимается там, где оно идёт.</summary>
    public const string Stop = "stop";

    /// <summary>Закрыть очередь иерархического запуска (T-263): снимается пометка с корня
    /// и его текущее задание, уже работающие потомки остаются доигрывать.</summary>
    public const string StopHierarchy = "stop-hierarchy";

    /// <summary>Закрыть очередь иерархии И снять задания всех работающих задач её поддерева
    /// (T-263): второй исход переспроса «остановить».</summary>
    public const string StopHierarchyAll = "stop-hierarchy-all";

    /// <summary>Заявка на ОСТАНОВКУ (любая из трёх): у неё другие правила и жизни, и разбора,
    /// чем у запуска, — проверять вид приходится в нескольких местах.</summary>
    public static bool IsStop(string kind) =>
        kind is Stop or StopHierarchy or StopHierarchyAll;

    /// <summary>Известный вид заявки; всё прочее считается одиночным запуском (совместимость
    /// со строками, приехавшими от сервера более старой версии).</summary>
    public static string Normalize(string kind) =>
        kind is Hierarchy or Stop or StopHierarchy or StopHierarchyAll ? kind : Task;
}

