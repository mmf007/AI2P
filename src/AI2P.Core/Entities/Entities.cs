/// <summary>
/// АДРЕС СЕРВЕРА В КЛАСТЕРЕ (T-141).
///
/// Серверы узнают друг друга по внутреннему ключу (<c>id</c>), а НЕ по адресу: адрес —
/// это только способ дозвониться, и уникальным он не бывает. Обычно публичный адрес есть
/// ровно у одного сервера кластера (чаще всего у дирижёра), а остальные стоят за NAT
/// с динамическими адресами внутренней сети — и называют себя <c>localhost</c>. Это
/// нормальное состояние: такой сервер работает «почти клиентом» — <b>с ним</b> сеанс
/// репликации начать нельзя, а <b>он сам</b> начинает его когда угодно.
///
/// Отсюда два правила, которые держит вся система:
/// <list type="bullet">
/// <item>двух серверов с одним адресом в списке не запрещено — совпадение адресов ничего
/// не значит, значение имеет только совпадение ключа;</item>
/// <item>петлевой адрес чужого сервера бесполезен (по нему мы обратимся к самим себе),
/// поэтому к такому серверу не ходят и его адрес не принимают репликацией поверх своего.</item>
/// </list>
/// </summary>
public static class ServerAddress
{
    /// <summary>Адрес, который у каждого компьютера означает «я сам»: обращаться по нему
    /// к ЧУЖОМУ серверу бессмысленно — попадёшь к себе.</summary>
    public static bool IsLoopback(string? hostname)
    {
        var value = (hostname ?? "").Trim().Trim('[', ']');
        return value.Length == 0
               || string.Equals(value, "localhost", StringComparison.OrdinalIgnoreCase)
               || value == "::1"
               || value.StartsWith("127.", StringComparison.Ordinal);
    }

    /// <summary>
    /// Почему к этому серверу нельзя обратиться; null — можно. Локальная запись — это мы сами,
    /// её петлевой адрес законен и ни к чему не мешает.
    ///
    /// ПЕТЛЕВОЙ АДРЕС — ЭТО «МЫ САМИ» НЕ ВСЕГДА (T-148): два экземпляра на одном компьютере
    /// различаются портом, и «localhost:5496» с нашего «localhost:5495» — законный адрес
    /// соседа, по которому он и правда отвечает. Поэтому, когда известна собственная запись
    /// (<paramref name="local"/>), петлевой адрес считается своим, только если совпадают
    /// и порт, и префикс пути. Именно так подключается второй сервер на той же машине:
    /// адрес дирижёра ему называет человек, и это «localhost:порт».
    /// </summary>
    public static string? Unreachable(ServerNode server, ServerNode? local = null)
    {
        if (server.IsLocal || !IsLoopback(server.Hostname))
        {
            return null;
        }
        // имя хоста вообще не задано — адреса нет, звонить некуда в любом случае
        if (server.Hostname.Trim().Length > 0 && local is not null
            && (server.Port != local.Port
                || !string.Equals(server.BasePath ?? "", local.BasePath ?? "",
                    StringComparison.OrdinalIgnoreCase)))
        {
            return null;
        }
        return Loc.T("msg.entities.1", (server.Name.Length > 0 ? server.Name : server.Hostname), server.Hostname);
    }
}

