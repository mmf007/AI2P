    /// <summary>Текст записи: урок/вывод, полезный при повторном выполнении.</summary>
    public string Text { get; set; } = "";

    /// <summary>
    /// ЗАГРУЖАТЬ ВСЕГДА (T-24-S0): запись идёт в задание независимо от отбора — её получает
    /// каждый исполнитель, даже если ни навык, ни тэги записи с задачей не сошлись. Так
    /// помечаются правила, без которых работать нельзя вовсе. Умолчание — выключено:
    /// иначе отбор, ради которого он и заведён, не отсекал бы ничего.
    /// </summary>
    public bool AlwaysLoad { get; set; }

    /// <summary>
    /// ТЭГИ записи (T-24-S0) — те же ключевые слова, что у задач и шаблонов (общий набор,
    /// справочника нет: <see cref="AI2P.Core.TaskTags"/>). Ими запись привязывается к теме
    /// работы («сборка», «репликация»), а не к навыку исполнителя.
    /// </summary>
    public List<string> Tags { get; set; } = [];
    /// <summary>Кем создана (исполнитель: человек или агент).</summary>
    public string? CreatedBy { get; set; }
    /// <summary>Кем изменена в последний раз.</summary>
    public string? UpdatedBy { get; set; }

    /// <summary>
    /// Сервер, создавший запись (ТЗ гл. 6, этап 42). Опыт накапливается везде, но каждый
    /// сервер правит и удаляет ТОЛЬКО свои записи; чужие видны для чтения.
    /// </summary>
    public string? ServerId { get; set; }
    /// <summary>Код сервера записи (S0, S1, …); в таблице не хранится.</summary>
    public string ServerCode { get; set; } = "";
    /// <summary>Запись другого сервера — только чтение; в таблице не хранится.</summary>
    public bool IsReadOnly { get; set; }
    /// <summary>
    /// Узел шаблона, к которому относится запись, удалён на дирижёре (ТЗ гл. 6, этап 42).
    /// Физически такая запись не трогается — удалить её может только сервер-владелец;
    /// в формах и в промпте агента она не показывается. В таблице не хранится.
    /// </summary>
    public bool IsOrphan { get; set; }

    /// <summary>Запись относится к проекту, а не к узлу шаблона (todo48).</summary>
    public bool IsProjectLevel => !string.IsNullOrEmpty(ProjectId);

    /// <summary>
    /// ОБЩЕЕ ПРАВИЛО РАБОТЫ (T-11-S0): запись не привязана ни к проекту, ни к узлу шаблона,
    /// поэтому её получает каждая задача организации. Отдельной колонки для этого не нужно:
    /// у записи опыта одно из двух полей привязки заполнено всегда, и пустые оба — это и есть
    /// признак общей записи.
    /// </summary>
    public bool IsGeneral => string.IsNullOrEmpty(ProjectId) && TemplateTaskId.Length == 0;
}

/// <summary>
/// ОБЪЕКТ ПРОЕКТА (ТЗ пп. 2.5–2.6; оживлён в T-259, версия 1.91). До T-259 сущность была
/// объявлена и не использовалась ни одной строкой кода — таблица <c>objects</c> в схеме
/// была, а списка, формы и сервиса не было.
///
/// Объект — это то, на что задача СССЫЛАЕТСЯ, а не то, что она делает: персонаж ролика,
/// локация, реквизит, стиль, эталонная картинка, обученный адаптер LoRA; а по ТЗ п. 2.6 —
/// ещё и файл, оборудование или программа с MCP-интерфейсом. Список объектов СВОЙ У
/// КАЖДОГО ПРОЕКТА (<see cref="ProjectId"/> обязателен): персонажи одного ролика не имеют
/// смысла в другом.
///
/// Объекты образуют ИЕРАРХИЮ (<see cref="ParentId"/>): персонаж описывается не одной
/// картинкой, поэтому у него внутренний список эталонных кадров — это его дочерние объекты.
/// Отдельной таблицы «файлы объекта» нет намеренно: у кадра те же поля (имя, тэги, паспорт,
/// путь), и второй сущностью он был бы копией этой.
///
/// В промпт объект попадает ССЫЛКОЙ <c>@obj:OBJ-3</c> в описании задачи
/// (<see cref="ObjectRefs"/>): медиа-модель получает промптом ТОЛЬКО описание задачи и
/// ничего больше (наука T-251), поэтому единственный способ дать ей паспорт персонажа —
/// подставить его в это описание.
/// </summary>
public sealed class ObjectItem : Entity
{
    /// <summary>Проект-владелец. Пусто быть не должно: список объектов — у проекта.</summary>
    public string? ProjectId { get; set; }

    /// <summary>Объект-родитель (T-259): внутренний список объекта. Пусто — объект верхнего
    /// уровня. Родитель обязан лежать в ТОМ ЖЕ проекте — иначе список проекта показывал бы
    /// детей чужого проекта (то же правило, что у подзадач, T-201).</summary>
    public string? ParentId { get; set; }

    /// <summary>Название — то, чем объект зовут люди и по чему его ищут в списке.</summary>
    public string Name { get; set; } = "";

    /// <summary>Вид: <see cref="ObjectKinds"/> — character / location / prop / style /
    /// image / lora / file / hardware / media.</summary>
    public string Type { get; set; } = ObjectKinds.Character;

    /// <summary>Путь файла (относительно папки проекта) либо адрес: эталонный кадр
    /// персонажа, картинка локации, файл.</summary>
    public string PathOrUrl { get; set; } = "";

    /// <summary>
    /// ПАСПОРТ объекта — тот самый дословный текст, который уезжает в промпт генерации:
    /// внешность персонажа, освещение локации, ограничения стиля. Markdown.
    /// </summary>
    public string Description { get; set; } = "";

    public string MetaJson { get; set; } = "{}";

    /// <summary>Неактивный объект не предлагается в подстановке и стоит в списке погашенным;
    /// ссылки на него при этом не рвутся — это не удаление.</summary>
    public bool IsActive { get; set; } = true;

    /// <summary>Путь обученного адаптера LoRA (T-259, черновик): само обучение будет
    /// отдельной работой, а место для файла и состояние заведены сразу.</summary>
    public string LoraPath { get; set; } = "";

    /// <summary>Состояние LoRA: <see cref="LoraStates"/> — none / planned / training / ready.</summary>
    public string LoraStatus { get; set; } = LoraStates.None;

    /// <summary>
    /// ТЕКУЩИЙ ДАТАСЕТ объекта (T-274) — тот из дочерних датасетов, в который ложатся новые
    /// кадры и по которому идёт обучение. Пусто — датасета ещё нет: первый заводится сам,
    /// как только добавят первый кадр.
    ///
    /// Полем формы объекта НЕ является: правится только редактором LoRA своим вызовом
    /// (<c>PUT /objects/{id}/lora/dataset/current</c>), а обычное сохранение объекта его не
    /// трогает — иначе форма, открытая до смены датасета, вернула бы прежний своим
    /// сохранением.
    /// </summary>
    public string? CurrentDatasetId { get; set; }

    /// <summary>
    /// НАСТРОЙКИ КОНТРОЛЯ КАРТИНОК самого датасета (T-274) — JSON
    /// <see cref="LoraDatasetLimits"/>; пусто у объектов, которые датасетом не являются.
    /// Переписываются из общих настроек при заведении датасета и дальше правятся здесь:
    /// у разных моделей разные требования к кадрам, и одно значение на всё приложение
    /// означало бы «пересобери датасет, когда сменишь модель».
    /// </summary>
    public string DatasetJson { get; set; } = "";

    /// <summary>Тэги объекта (T-259). Своя группа, отдельная от тэгов задач: справочника
    /// у них так же нет — набор тэгов проекта это DISTINCT по <c>object_tags</c>.
    /// В таблице <c>objects</c> не хранится (связь), приведение — <see cref="TaskTags"/>.</summary>
    public List<string> Tags { get; set; } = [];

    /// <summary>Для MCP-программ: stdio / http.</summary>
    public string? Transport { get; set; }
    public string? CommandOrUrl { get; set; }
    public string? ToolsCacheJson { get; set; }
    public string? RulesJson { get; set; }

    /// <summary>Сколько у объекта детей (внутренний список). В таблице не хранится —
    /// считается сервисом при выдаче списка, чтобы список рисовался одним запросом.</summary>
    public int ChildCount { get; set; }

    /// <summary>
    /// СЕРВЕР-ВЛАДЕЛЕЦ ОБЪЕКТА (T-102-S0) — то же правило, что у задач (ТЗ гл. 6): объект
    /// правится только на своём сервере, остальным он едет журналом изменений и виден там
    /// только для чтения. До этой версии сервера у объекта не было вовсе, и правил его тот,
    /// кто сегодня дирижёр, — то есть объект принадлежал РОЛИ, а не компьютеру (та же мина,
    /// которую T-1-S0 чинил у задач). Пусто — объект приехал от партнёра прежней версии:
    /// по общему правилу его правит дирижёр, пока сторож не запишет владельца явно.
    /// </summary>
    public string? ServerId { get; set; }

    /// <summary>Код сервера объекта (S0, S1, …); в таблице не хранится.</summary>
    public string ServerCode { get; set; } = "";

    /// <summary>Имя сервера объекта; в таблице не хранится.</summary>
    public string ServerName { get; set; } = "";

    /// <summary>Объект принадлежит другому серверу — здесь он только читается;
    /// в таблице не хранится.</summary>
    public bool IsReadOnly { get; set; }
}

/// <summary>
/// Виды объектов проекта (T-259). Первые пять — то, ради чего объекты заводились: постоянные
/// персонажи и обстановка роликов (T-251, п. 2.3). <c>file</c> и <c>hardware</c> — из ТЗ п. 2.6.
/// <c>media</c> — МЕДИАТЕКА ПРОЕКТА (T-111-S0).
///
/// ВИДА <c>mcp</c> ЗДЕСЬ БОЛЬШЕ НЕТ (решение заказчика, T-111-S0). Он был заготовкой ТЗ п. 2.6
/// («объект — программа с MCP-интерфейсом»), но записей такого вида не завелось ни одной, а по
/// смыслу это не объект ПРОЕКТА: подключение к серверу MCP нужно всей организации, поэтому оно
/// стало записью плагина уровня организации (<see cref="PluginRecord"/>). Колонки таблицы
/// <c>objects</c> (<c>transport</c>, <c>command_or_url</c>, <c>tools_cache_json</c>,
/// <c>rules_json</c>) намеренно ОСТАВЛЕНЫ: удаление колонки в SQLite — это пересоздание таблицы
/// с переносом данных и правкой репликации ради четырёх пустых полей. Они просто перестают
/// заполняться.
/// </summary>
public static class ObjectKinds
{
    public const string Character = "character";
    public const string Location = "location";
    public const string Prop = "prop";
    public const string Style = "style";
    /// <summary>Эталонный кадр: обычно ребёнок персонажа или локации.</summary>
    public const string Image = "image";
    /// <summary>
    /// ДАТАСЕТ (T-274) — папка эталонных кадров для обучения адаптера. Заведён отдельным
    /// видом ровно затем, чтобы кадры не лежали вперемешку с логическими детьми объекта:
    /// до этого каждая картинка датасета была прямым ребёнком объекта, и у персонажа, у
    /// которого есть свои дочерние объекты, иерархия превращалась в кашу из полусотни
    /// кадров. Теперь кадры — дети ДАТАСЕТА, а датасетов у объекта бывает несколько:
    /// у разных моделей разные требования к картинкам.
    /// </summary>
    public const string Dataset = "dataset";
    /// <summary>Обученный адаптер персонажа.</summary>
    public const string Lora = "lora";
    public const string File = "file";
    public const string Hardware = "hardware";

    /// <summary>
    /// МЕДИАРЕСУРС ПРОЕКТА (T-111-S0) — снятый дубль, звуковая дорожка, титр, готовая сборка.
    /// Медиатека проекта это НЕ третий параллельный список файлов, а ПРЕДСТАВЛЕНИЕ над теми же
    /// объектами проекта (T-259/T-266): отбор по этому виду плюс метаданные ролика в
    /// <see cref="ObjectItem.MetaJson"/> (<see cref="MediaMeta"/>).
    ///
    /// Заведён отдельным видом, а не отбором по существующим: у медиаресурса своя жизнь
    /// (сцена, дубль, длительность, задание-источник) и свой экран, а «эталонный кадр»
    /// (<see cref="Image"/>) — это вход генерации, вещь совсем другого назначения. Отбор
    /// по существующим видам смешал бы их в одну кучу необратимо.
    /// </summary>
    public const string Media = "media";

    /// <summary>Все виды в порядке показа в форме и в списке.</summary>
    public static readonly string[] All =
        [Character, Location, Prop, Style, Image, Dataset, Lora, File, Hardware, Media];

    /// <summary>Вид известен системе; неизвестный приезжает только правкой базы руками.</summary>
    public static bool IsKnown(string? kind) =>
        kind is not null && Array.IndexOf(All, kind) >= 0;

    /// <summary>
    /// ОТБОР ПО ВИДАМ (T-276): «character,image» — в список видов. Порядок — как в
    /// <see cref="All"/>, повторы снимаются.
    ///
    /// Неизвестные коды ОТБРАСЫВАЮТСЯ, а не превращают отбор в пустой результат: строка
    /// приходит из запроса, и опечатка в ней не должна опустошать список объектов —
    /// пустой список человек читает как «объектов нет», а не как «фильтр не понят».
    /// Пустой итог означает «отбора нет» ровно по той же причине.
    /// </summary>
    public static List<string> Parse(string? kinds)
    {
        var result = new List<string>();
        foreach (var part in (kinds ?? "").Split(',',
                     StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
        {
            var code = part.ToLowerInvariant();
            if (IsKnown(code) && !result.Contains(code, StringComparer.Ordinal))
            {
                result.Add(code);
            }
        }
        return result.OrderBy(k => Array.IndexOf(All, k)).ToList();
    }

    /// <summary>
    /// Название вида словами. <paramref name="lang"/> — язык читателя: у медиа-модели и у
    /// человека это язык установки (null), у агента — язык его команды (T-190). Название
    /// неизвестного вида — сам код: придумывать за него перевод не за чем.
    /// </summary>
    public static string Title(string kind, string? lang = null) =>
        IsKnown(kind) ? Loc.In(lang, "object.kind." + kind) : kind;
}

/// <summary>
/// Состояние адаптера LoRA у объекта (T-259, черновик). Сами методы создания и обучения
/// будут отдельной работой — здесь только место, куда их результат ляжет, и признак,
/// по которому форма показывает, на каком шаге объект стоит.
/// </summary>
public static class LoraStates
{
    /// <summary>Адаптера нет и не планировался.</summary>
    public const string None = "none";
    /// <summary>Решено обучать: набираются эталонные кадры.</summary>
    public const string Planned = "planned";
    /// <summary>Обучение идёт.</summary>
    public const string Training = "training";
    /// <summary>Файл адаптера готов и лежит по <c>LoraPath</c>.</summary>
    public const string Ready = "ready";

    public static readonly string[] All = [None, Planned, Training, Ready];

    public static bool IsKnown(string? state) =>
        state is not null && Array.IndexOf(All, state) >= 0;
}

/// <summary>
/// ОБУЧЕНИЕ АДАПТЕРА ПОД ОДНУ МОДЕЛЬ (T-12-S1, версия 1.95) — строка вкладки «Модели»
/// редактора LoRA.
///
/// Почему это отдельная строка, а не поле объекта: адаптер обучается ПОД КОНКРЕТНУЮ модель
/// (веса Kandinsky T2V и Kandinsky I2V разные, и файл, обученный для одной, к другой не
/// подходит), поэтому у одного персонажа адаптеров столько, сколько моделей его умеют.
/// Пара «объект + модель» уникальна: обучать один и тот же адаптер дважды под одну модель
/// незачем, для этого есть переобучение (<see cref="Status"/> возвращается в
/// <see cref="LoraModelStates.Training"/>).
///
/// Поля <c>ObjectItem.LoraPath</c> и <c>ObjectItem.LoraStatus</c> при этом остаются и
/// означают «текущий адаптер объекта»: их читает подстановка адаптера в модель при
/// генерации. Успешное обучение проставляет их последним обученным файлом.
/// </summary>
public sealed class ObjectLoraModel : Entity
{
    /// <summary>Объект вида <see cref="ObjectKinds.Lora"/>, которому принадлежит строка.</summary>
    public string ObjectId { get; set; } = "";

    /// <summary>Запись справочника моделей, под которую обучается адаптер.</summary>
    public string ModelId { get; set; } = "";

    /// <summary>Состояние обучения: <see cref="LoraModelStates"/>.</summary>
    public string Status { get; set; } = LoraModelStates.None;

    /// <summary>Файл обученного адаптера (то, что подставляется модели при генерации).</summary>
    public string Path { get; set; } = "";

    /// <summary>
    /// Сообщение об ошибке обучения — ровно то, что сказали процесс обучения или API
    /// провайдера. Показывается подсказкой на слове «ошибка» в списке: без него человеку
    /// остаётся только слово «ошибка», по которому чинить нечего.
    /// </summary>
    public string Error { get; set; } = "";

    /// <summary>
    /// ДАТАСЕТ, ПО КОТОРОМУ ОБУЧИЛИ (T-274) — объект вида <see cref="ObjectKinds.Dataset"/>,
    /// кадрами которого получен лежащий в <see cref="Path"/> файл. Пусто — обучения ещё не
    /// было либо оно шло по старому датасету (кадрами самого объекта, до версии 1.98).
    ///
    /// Хранится затем, чтобы повторный запуск не подменил датасет молча: у объекта их
    /// несколько, текущий переключают, а адаптер, обученный на одних кадрах, от адаптера
    /// на других отличается ровно всем — со стороны это «переобучил, и персонаж стал чужим».
    /// </summary>
    public string DatasetId { get; set; } = "";

    /// <summary>Название запомненного датасета — для переспроса; в таблице не хранится.</summary>
    public string DatasetName { get; set; } = "";

    /// <summary>Когда обучение началось; null — ни разу не запускалось.</summary>
    public DateTime? StartedAt { get; set; }

    /// <summary>Когда обучение кончилось — удачно или ошибкой.</summary>
    public DateTime? FinishedAt { get; set; }

    /// <summary>Номер записи справочника (M-7) — «Id модели» списка. В таблице не хранится.</summary>
    public string ModelDisplayId { get; set; } = "";

    /// <summary>Имя записи справочника (Kandinsky-5-T2V) — «Код модели» списка.
    /// В таблице не хранится.</summary>
    public string ModelName { get; set; } = "";

    /// <summary>Модель сейчас умеет работать с LoRA (её профайл это объявляет, T-13-S1).
    /// В таблице не хранится: настройку правят в справочнике, и строка обучения обязана
    /// показывать сегодняшнее положение дел, а не то, что было при заведении.</summary>
    public bool LoraSupported { get; set; }

    /// <summary>Почему модель не работает с LoRA — код <see cref="LoraReasons"/>;
    /// в таблице не хранится.</summary>
    public string LoraReason { get; set; } = "";

    /// <summary>
    /// ЗАДАЧА, КОТОРАЯ ОБУЧАЕТ (T-157-S0). С этой версии обучение идёт не фоном сервиса, а
    /// ЗАДАЧЕЙ с исполнителем «авто ПО»: у неё есть консоль, лог, кнопка остановки, планирование
    /// и место в иерархии. Здесь — ссылка на неё: в списке моделей объекта состояние
    /// «обучается» кликабельно и ведёт в карточку задачи.
    ///
    /// Это же поле избавляет задачу от СВОИХ полей с параметрами запуска: коннектор по
    /// идентификатору задачи находит ОБРАТНЫМ поиском эту строку
    /// (<c>ObjectService.LoraModelByTrainTask</c>), а в ней уже есть всё — объект, датасет,
    /// модель и настройка <c>lora.train</c> её профайла.
    /// </summary>
    public string TrainTaskId { get; set; } = "";

    /// <summary>Номер задачи обучения (T-15) — надпись ссылки. В таблице не хранится.</summary>
    public string TrainTaskDisplayId { get; set; } = "";
}

/// <summary>
/// Состояние обучения адаптера под одну модель (T-12-S1). Три состояния из задания —
/// «необучена», «обучается», «обучена» — плюс четвёртое, без которого первые три врут:
/// упавшее обучение обязано отличаться от неначатого, иначе человек жмёт «обучить» снова
/// и снова, не зная, что не так.
/// </summary>
public static class LoraModelStates
{
    /// <summary>Необучена: строку завели, обучение не запускали (или оно снято).</summary>
    public const string None = "none";
    /// <summary>Обучается: процесс идёт прямо сейчас.</summary>
    public const string Training = "training";
    /// <summary>Обучена: файл адаптера лежит по <see cref="ObjectLoraModel.Path"/>.</summary>
    public const string Ready = "ready";
    /// <summary>Ошибка: причина в <see cref="ObjectLoraModel.Error"/>.</summary>
    public const string Error = "error";

    public static readonly string[] All = [None, Training, Ready, Error];

    public static bool IsKnown(string? state) =>
        state is not null && Array.IndexOf(All, state) >= 0;
}

/// <summary>
/// ЗАПИСЬ ПЛАГИНА (T-111-S0) — шлюз в видеоредактор, конвертор, подключение к серверу MCP.
///
/// УРОВЕНЬ ОРГАНИЗАЦИИ, а не объект проекта: у объекта проекта есть проект-хозяин, а шлюз в
/// Shotcut нужен всем проектам организации сразу. Запись реплицируется обычным журналом
/// изменений (<c>ChangeLog.OrgTables</c>) — плагин объявили на одном сервере, видно его на всех.
///
/// ЧЕГО В ЗАПИСИ НЕТ И ПОЧЕМУ: НИ ОДНОГО ПУТИ К СОФТУ и никакой пометки «инициализировал
/// сервер такой-то». Установка плагина всегда локальная (решение заказчика, по образцу
/// локальной модели): реплицированный чужой путь ломает установку у соседа и «уже не уходит»
/// (наука T-164 про платформенные умолчания). Факт «установлен здесь», ручной путь и время
/// последней проверки лежат в <c>config.json</c> СЕРВЕРА (раздел <c>plugins</c>), секреты
/// подключения MCP — в <c>secrets/*.json</c>, как почтовый пароль.
///
/// <see cref="SettingsJson"/> — настройки САМОЙ ЗАПИСИ (то, что человек задаёт плагину: fps
/// экспорта, папка результата, имя профиля). Их состав объявляет манифест
/// (<c>PluginManifest</c>), а хранятся они свободным JSON: у каждого плагина свои поля,
/// и колонка на каждое означала бы миграцию схемы на каждый новый плагин.
/// </summary>
public sealed class PluginRecord
{
    public string Id { get; set; } = Guid.NewGuid().ToString();

    /// <summary>Номер записи, PLG-N (с суффиксом сервера вне дирижёра).</summary>
    public string DisplayId { get; set; } = "";

    /// <summary>Код плагина из манифеста: <c>editor.shotcut</c>. Уникален в организации —
    /// по нему же ищется каталог <c>plugins/&lt;код&gt;/</c> и раздел config.json.</summary>
    public string Code { get; set; } = "";

    /// <summary>Вид: <see cref="PluginKinds"/> — шлюз или подключение MCP.</summary>
    public string Kind { get; set; } = PluginKinds.Gateway;

    /// <summary>Название для человека (из манифеста; правится в форме).</summary>
    public string Name { get; set; } = "";

    /// <summary>Версия манифеста, по которой запись заведена: манифест дистрибутива
    /// обновляется вместе с программой, и по этому числу видно, что запись отстала.</summary>
    public int ManifestVersion { get; set; } = 1;

    /// <summary>Состояние: <see cref="PluginStates"/>.</summary>
    public string State { get; set; } = PluginStates.Declared;

    /// <summary>Настройки записи — свободный JSON по составу из манифеста.</summary>
    public string SettingsJson { get; set; } = "{}";

    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;
    public DateTime? DeletedAt { get; set; }
}

/// <summary>Виды плагинов (T-111-S0).</summary>
public static class PluginKinds
{
    /// <summary>ШЛЮЗ во внешнюю программу: Shotcut/Kdenlive (MLT XML), DaVinci Resolve (OTIO),
    /// Blender VSE, OpenShot, конвертор ffmpeg. Что он умеет — блок <c>actions</c> манифеста.</summary>
    public const string Gateway = "gateway";

    /// <summary>ПОДКЛЮЧЕНИЕ К СЕРВЕРУ MCP: вместо <c>actions</c> у манифеста блок
    /// <c>connection</c> (транспорт, команда или адрес, ссылка на секрет), а список
    /// инструментов сервер MCP называет сам при инициализации.</summary>
    public const string Mcp = "mcp";

    public static readonly string[] All = [Gateway, Mcp];

    public static bool IsKnown(string? kind) =>
        kind is not null && Array.IndexOf(All, kind) >= 0;

    public static string Title(string kind, string? lang = null) =>
        IsKnown(kind) ? Loc.In(lang, "plugin.kind." + kind) : kind;
}

/// <summary>
/// Состояния записи плагина (T-111-S0). Три, и они про РАЗНОЕ:
/// <list type="bullet">
/// <item><b>объявлен</b> — запись есть, работать ею нельзя: софт не найден либо
/// инициализация ещё не проходила. Это состояние новой записи;</item>
/// <item><b>инициализирован</b> — плагин прошёл инициализацию (действия зарегистрированы
/// в справочнике, опыт записан) и годится к работе;</item>
/// <item><b>выключен</b> — человек выключил его руками. От «объявлен» отличается тем, что
/// это РЕШЕНИЕ, а не отсутствие условий, и повторная инициализация его не снимает;</item>
/// <item><b>снят</b> — обратное инициализации (T-112-S0): действия справочника и записи
/// опыта удалены, а НАСТРОЙКИ ЗАПИСИ и пер-серверный ручной путь остались. От «выключен»
/// отличается тем, что там всё зарегистрированное на месте и включается мгновенно, а здесь
/// плагин надо инициализировать заново — но не вводя настройки заново.</item>
/// </list>
/// Пятого состояния — «софт ищется» — в базе НЕТ намеренно: найден ли софт, у каждого
/// сервера свой ответ, он считается на месте и показывается колонкой своего сервера.
/// Состояние реплицируется вместе с записью, а «установлен ли софт ЗДЕСЬ» — нет: это
/// пер-серверная вещь из config.json (см. <see cref="PluginRecord"/>).
/// </summary>
public static class PluginStates
{
    public const string Declared = "declared";
    public const string Initialized = "initialized";
    public const string Disabled = "disabled";

    /// <summary>Снят (T-112-S0): регистрация отменена, настройки записи сохранены.</summary>
    public const string Removed = "removed";

    public static readonly string[] All = [Declared, Initialized, Disabled, Removed];

    public static bool IsKnown(string? state) =>
        state is not null && Array.IndexOf(All, state) >= 0;

    public static string Title(string state, string? lang = null) =>
        IsKnown(state) ? Loc.In(lang, "plugin.state." + state) : state;
}
