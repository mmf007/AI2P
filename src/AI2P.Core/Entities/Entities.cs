/// <summary>
/// Раздельное владение строками в кластере (ТЗ гл. 6, этап 42). У каждой строки ровно один
/// сервер-писатель: остальные видят её только для чтения. Это снимает конфликты одновременной
/// правки и убирает межсерверный запуск заданий — задание всегда выполняется у владельца.
///
/// Правило одно на все сущности: сервер указан — правит только он; сервер не указан —
/// правит только дирижёр.
/// </summary>
public static class Ownership
{
    /// <summary>Строку с таким владельцем можно править на этом сервере (ТЗ гл. 6).</summary>
    /// <param name="ownerServerId">Внутренний ключ сервера-владельца; пусто — владельца нет.</param>
    /// <param name="localServerId">Внутренний ключ ЭТОГО сервера.</param>
    /// <param name="isConductor">Этот сервер — дирижёр организации.</param>
    public static bool CanWrite(string? ownerServerId, string localServerId, bool isConductor) =>
        ownerServerId is { Length: > 0 } owner
            ? owner == localServerId
            : isConductor;
}

