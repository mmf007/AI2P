namespace AI2P.Core.Entities;

/// <summary>
/// Общие поля всех сущностей (ТЗ п. 6.4.2): UUID + display_id, даты UTC, мягкое удаление.
/// </summary>
public abstract class Entity
{
    public string Id { get; set; } = Guid.NewGuid().ToString();
    public string DisplayId { get; set; } = "";
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
    public DateTime? DeletedAt { get; set; }
}

/// <summary>
/// Организация (ТЗ п. 2.15, гл. 6; этап 40) — контейнер ВСЕХ рабочих данных: проектов,
/// задач, шаблонов, команд, исполнителей, справочников и файлов. У каждой организации своя
/// БД и свой подкаталог хранилища (<c>data/orgs/&lt;display_id&gt;/</c>), поэтому нумерация
/// сущностей и счётчики у неё свои, а пересечение организаций возможно только через
/// экспорт/импорт. Сама организация живёт в СЕРВЕРНОЙ БД — вне организаций.
/// </summary>
public sealed class Organization : Entity
{
    public string Name { get; set; } = "";
    /// <summary>Код в URL: <c>/ai2p/&lt;код&gt;/…</c> (ТЗ гл. 11). Уникален среди неудалённых,
    /// только латиница/цифры/дефис — иначе ссылки нечитаемы и небезопасны.</summary>
    public string Code { get; set; } = "";
    /// <summary>Неактивная организация не открывается и не предлагается в переключателе.
    /// Пока архивации нет, удаление организации делается именно снятием активности (ТЗ гл. 6).</summary>
    public bool IsActive { get; set; } = true;
    /// <summary>Вошедший — участник этой организации (есть исполнитель с его аккаунтом).
    /// В БД не хранится: заполняется сервисом при выдаче списка наружу.</summary>
    public bool IsMember { get; set; }

    /// <summary>
    /// ВОШЕДШИЙ ЕЩЁ НЕ УЧАСТНИК, НО МОЖЕТ ВСТУПИТЬ САМ (T-186-S0). В БД не хранится —
    /// считается при выдаче списка наружу.
    ///
    /// Организация, приехавшая на этот сервер репликацией (дирижёр включил его в неё
    /// галочкой в своей форме), участников здесь не заводит: исполнителя заявителя
    /// заводит дирижёр, а при включении галочкой заявителя нет вовсе. Поэтому человек
    /// за этим компьютером организацию не видел ни в переключателе, ни кнопкой «открыть»,
    /// хотя её база уже лежит у него на диске. Вступить может ХОЗЯИН ЭТОГО КОМПЬЮТЕРА
    /// (владелец системы или локальный администратор сервера): данные организации у него
    /// физически есть, и запрет ему доступа ничего не защищает.
    /// </summary>
    public bool CanJoin { get; set; }

    /// <summary>
    /// Имя каталога организации НА ЭТОМ компьютере (<c>data/orgs/&lt;имя&gt;</c>, T-148-S0).
    /// С номером совпадает не всегда: организация, чей номер когда-то столкнулся с приехавшей,
    /// лежит в каталоге с приставкой (<c>ORG-1-2</c>). В БД организации не хранится —
    /// заполняется при выдаче списка наружу, показывается в настройках и в переспросе удаления.
    /// </summary>
    public string DirName { get; set; } = "";

    /// <summary>Почему организацию нельзя удалить с этого сервера — словами; пусто — можно
    /// (T-148-S0). Считается при выдаче списка, как у сервера: кнопка удаления должна быть
    /// погашена с объяснением, а не исчезать молча.</summary>
    public string DeleteProblem { get; set; } = "";

    /// <summary>
    /// Код организации для URL: латиница, цифры и дефис в нижнем регистре. Кириллица
    /// транслитерируется — код попадает в ссылки на задачи, которые пересылают друг другу,
    /// и должен читаться и набираться руками. Правило лежит здесь, а не в хранилище:
    /// его же применяет UI, подсказывая код по названию.
    /// </summary>
    public static string NormalizeCode(string source)
    {
        var sb = new System.Text.StringBuilder();
        foreach (var ch in source.Trim().ToLowerInvariant())
        {
            if (ch is >= 'a' and <= 'z' or >= '0' and <= '9')
            {
                sb.Append(ch);
            }
            else if (Translit.TryGetValue(ch, out var latin))
            {
                sb.Append(latin);
            }
            else if (sb.Length > 0 && sb[^1] != '-')
            {
                sb.Append('-');
            }
        }
        var code = sb.ToString().Trim('-');
        return code.Length == 0 ? "org" : code[..Math.Min(code.Length, 40)].Trim('-');
    }

    private static readonly Dictionary<char, string> Translit = new()
    {
        ['а'] = "a", ['б'] = "b", ['в'] = "v", ['г'] = "g", ['д'] = "d", ['е'] = "e", ['ё'] = "e",
        ['ж'] = "zh", ['з'] = "z", ['и'] = "i", ['й'] = "y", ['к'] = "k", ['л'] = "l", ['м'] = "m",
        ['н'] = "n", ['о'] = "o", ['п'] = "p", ['р'] = "r", ['с'] = "s", ['т'] = "t", ['у'] = "u",
        ['ф'] = "f", ['х'] = "h", ['ц'] = "c", ['ч'] = "ch", ['ш'] = "sh", ['щ'] = "sch",
        ['ъ'] = "", ['ы'] = "y", ['ь'] = "", ['э'] = "e", ['ю'] = "yu", ['я'] = "ya",
    };
}

/// <summary>
/// Сервер кластера (ТЗ п. 2.15, гл. 6; этап 41). Сервер — сущность уровня УСТАНОВКИ, а не
/// организации: с организациями он связан «многие ко многим» (<see cref="OrgServer"/>), то
/// есть один сервер обслуживает несколько организаций, а организация живёт на нескольких
/// серверах. Локальный сервер есть всегда и в списке идёт первым; его адрес и каталоги
/// правятся не здесь, а в config.json — от них зависит сам запуск приложения, поэтому их
/// должно быть возможно исправить и при неработающем сервере (ТЗ гл. 10).
/// </summary>
public sealed class ServerNode : Entity
{
    /// <summary>Имя сервера для человека (в кластере встречаются одинаковые адреса за NAT).</summary>
    public string Name { get; set; } = "";
    public string Protocol { get; set; } = "http";
    /// <summary>Имя хоста или публичный IP: по нему сервер зовут снаружи и по нему же
    /// формируются ссылки на задачи (ТЗ гл. 11).</summary>
    public string Hostname { get; set; } = "localhost";
    public int Port { get; set; } = 5480;

    /// <summary>
    /// ВТОРОЙ (ВНЕШНИЙ) АДРЕС СЕРВЕРА (T-50-S0). Пусто — второго адреса нет, и всё работает
    /// как раньше, по одной паре имя/порт.
    ///
    /// Зачем: у сервера за NAT адресов два — внутренний (<see cref="Hostname"/>, по нему его
    /// зовут соседи в своей сети) и внешний, по которому его видно снаружи. Пока ноутбук
    /// в офисе, до соседа доходит первый адрес; уехал — доходит только второй. Поэтому
    /// обращение к серверу пробует адреса ПО ОЧЕРЕДИ (<c>ClusterClient</c>), а не выбирает
    /// один раз навсегда.
    ///
    /// Значение своего сервера берётся из <c>config.json</c> (<c>ui.hostname2</c>) и, как
    /// и остальной адрес, уезжает соседям обычной репликацией: свой внешний адрес знает
    /// только сам сервер, называть его руками на каждом соседе незачем.
    /// </summary>
    public string Hostname2 { get; set; } = "";

    /// <summary>Порт второго адреса; <c>null</c> — тот же, что <see cref="Port"/> (на роутере
    /// проброшенный порт часто не совпадает с портом сервера). Без <see cref="Hostname2"/>
    /// не значит ничего: порт без имени — не адрес.</summary>
    public int? Port2 { get; set; }

    /// <summary>Префикс URL после порта (ТЗ гл. 11): <c>/ai2p</c>.</summary>
    public string BasePath { get; set; } = "/ai2p";
    /// <summary>Это сам данный сервер.</summary>
    public bool IsLocal { get; set; }
    /// <summary>Неактивный сервер не опрашивается и не участвует в репликации. Пока архивации
    /// нет, «удаление» сервера делается именно снятием активности (ТЗ гл. 6).</summary>
    public bool IsActive { get; set; } = true;

    /// <summary>Адрес обращения: <c>protocol://hostname:port{basePath}</c>.</summary>
    public string Url => $"{Protocol}://{Hostname}:{Port}{BasePath}";

    /// <summary>Второй адрес задан (T-50-S0): имя есть — значит по нему можно пробовать
    /// звонить. Порт без имени адресом не считается.</summary>
    public bool HasAddress2 => Hostname2.Trim().Length > 0;

    /// <summary>Второй (внешний) адрес обращения; пусто — второго адреса нет (T-50-S0).</summary>
    public string Url2 => HasAddress2
        ? $"{Protocol}://{Hostname2.Trim()}:{Port2 ?? Port}{BasePath}"
        : "";

    /// <summary>Организации сервера (ТЗ п. 2.15): в БД не хранится — заполняется сервисом
    /// при выдаче наружу, чтобы форма сервера показывала его список организаций.</summary>
    public List<OrgServer> Orgs { get; set; } = [];

    /// <summary>Состояние исходящей заявки на подключение к чужому дирижёру (ТЗ гл. 6):
    /// <c>""</c> — заявки не было, иначе <see cref="OrgServerStatus"/>.</summary>
    public string JoinStatus { get; set; } = "";
    /// <summary>Код организации, к которой поданa заявка; пусто — заявки не было.</summary>
    public string JoinOrgCode { get; set; } = "";
    /// <summary>Ссылка на заявку у принимающего сервера — по ней спрашивают её состояние.</summary>
    public string JoinRef { get; set; } = "";
    /// <summary>Текст последней ошибки связи с сервером; пусто — ошибок не было.</summary>
    public string LastError { get; set; } = "";

    /// <summary>
    /// Интервал автоматической репликации, секунды (ТЗ гл. 6, этап 43): <c>null</c> —
    /// автоматически не реплицировать, только по кнопке. Минимум 30 с. Принадлежит записи
    /// сервера, а не связи с организацией: сервер реплицируется одним ритмом по всем своим
    /// организациям — сначала одна целиком, потом другая. Отсчёт ведут ОБА конца пары,
    /// поэтому это единственная часть записи сервера, которая реплицируется.
    /// </summary>
    public int? ReplIntervalSec { get; set; }

    /// <summary>Интервал повтора после ошибки репликации, секунды; минимум 15 с.
    /// <c>null</c> — повторять через обычный интервал.</summary>
    public int? ReplRetrySec { get; set; }

    /// <summary>Дирижёр организации, с которой сервер реплицируется, — здесь не хранится:
    /// подставляется сервисом (у рядового сервера партнёр по репликации всегда дирижёр).</summary>
    public bool IsConductorSomewhere { get; set; }

    /// <summary>Почему запись сервера нельзя удалить (T-141); пусто — можно. В таблице
    /// не хранится: подставляется при выдаче списка наружу, чтобы кнопка удаления была
    /// погашена с объяснением, а не пропадала молча.</summary>
    public string DeleteProblem { get; set; } = "";

    /// <summary>
    /// КОД, ПОД КОТОРЫМ ЭТОТ СЕРВЕР ЗОВУТ В КЛАСТЕРЕ (T-170-S0): S0, S1, … — независимо от
    /// конкретной организации; пусто — сервер не связан ни с одной. В таблице не хранится
    /// (код принадлежит связи <see cref="OrgServer"/>), подставляется при выдаче списка.
    ///
    /// Нужен форме организации: в списке серверов код обязан быть виден ВСЕГДА, в том числе
    /// у сервера, который в эту организацию ещё не включён. Без него человек видел пустое
    /// место, а после отметки галочкой — выданный тут же новый код, которым в кластере
    /// не зовут никого (жалоба T-170-S0).
    /// </summary>
    public string ClusterCode { get; set; } = "";
}

/// <summary>
/// Состояние репликации пары «организация — сервер-партнёр» (ТЗ гл. 6, этап 43): курсоры,
/// отставание, время следующего запуска, конфликты и последняя ошибка. Это же — содержимое
/// экрана диагностики: без него разбираться с расхождением реплик было бы нечем.
/// </summary>
public sealed class ReplicationState
{
    public string OrgId { get; set; } = "";
    public string ServerId { get; set; } = "";

    /// <summary>Докуда дочитан журнал изменений партнёра (БД организации).</summary>
    public long PullCursor { get; set; }

    /// <summary>Докуда партнёр принял наш журнал изменений.</summary>
    public long PushCursor { get; set; }

    /// <summary>То же для серверной БД: аккаунты, организация и её серверы.</summary>
    public long ServerPullCursor { get; set; }

    public long ServerPushCursor { get; set; }

    /// <summary>idle — ждёт, running — идёт репликация, error — прошлый сеанс не удался.</summary>
    public string Status { get; set; } = ReplicationStatuses.Idle;

    public DateTime? LastRunAt { get; set; }
    public DateTime? LastOkAt { get; set; }

    /// <summary>Когда сработает автоматическая репликация; null — интервал не задан
    /// («ручная») либо репликация идёт прямо сейчас — отсчёт на это время останавливается.</summary>
    public DateTime? NextRunAt { get; set; }

    public string LastError { get; set; } = "";
    public int Conflicts { get; set; }
    public string LastConflict { get; set; } = "";

    /// <summary>Изменений принято и отдано за последний сеанс.</summary>
    public int Received { get; set; }

    public int Sent { get; set; }

    // --- файлы (ТЗ гл. 6, п. 7 плана; этап 44): за последний сеанс ---

    /// <summary>Файлов принято и отдано за последний сеанс.</summary>
    public int FilesReceived { get; set; }

    public int FilesSent { get; set; }

    /// <summary>Байт принято и отдано за последний сеанс — по ним видно масштаб переноса
    /// медиа, ради которого папка <c>Common</c> и заведена.</summary>
    public long BytesReceived { get; set; }

    public long BytesSent { get; set; }

    // --- очередь повтора (T-160) ---

    /// <summary>Сколько строк база принять отказалась и ждёт повтора. Не ноль — часть данных
    /// ещё не доехала, но сеанс идёт дальше: раньше такая строка останавливала репликацию
    /// целиком, и организация оставалась скопированной наполовину.</summary>
    public int Pending { get; set; }

    /// <summary>Последний отказ словами: таблица, ключ строки и причина от базы.</summary>
    public string LastPending { get; set; } = "";

    public DateTime UpdatedAt { get; set; }
}

/// <summary>Состояние репликации сервера (ТЗ гл. 6, этап 43).</summary>
public static class ReplicationStatuses
{
    /// <summary>Сеанса нет: либо ждём срока, либо репликация только ручная.</summary>
    public const string Idle = "idle";

    /// <summary>Сеанс идёт прямо сейчас — в списке серверов виден прогресс-бар.</summary>
    public const string Running = "running";

    /// <summary>Прошлый сеанс закончился ошибкой; повтор — через интервал ошибки.</summary>
    public const string Error = "error";
}

/// <summary>
/// Связь «организация ↔ сервер» (ТЗ п. 2.15, гл. 6; этап 41): у организации свой список
/// серверов, у сервера — свой список организаций. Код (<c>S0</c>, <c>S1</c>, …) и признак
/// дирижёра принадлежат именно связи: сервер может быть дирижёром одной организации и
/// обычным участником другой, а номера задач получают суффикс кода в рамках организации.
/// </summary>
public sealed class OrgServer : Entity
{
    public string OrgId { get; set; } = "";
    /// <summary>Внутренний ключ сервера (unid): им серверы узнают друг друга при репликации,
    /// адрес для этого не годится — он меняется (ТЗ гл. 6, todo41 п. 6).</summary>
    public string ServerId { get; set; } = "";
    /// <summary>Код сервера в организации: S0, S1, … (ТЗ гл. 6 «Номера задач»).
    /// Выдаёт дирижёр; не переиспользуется после вывода сервера из кластера.</summary>
    public string Code { get; set; } = "S0";
    /// <summary>Дирижёр организации; он ровно один (ТЗ гл. 6).</summary>
    public bool IsConductor { get; set; }
    public bool IsActive { get; set; } = true;
    /// <summary>Состояние связи: подтверждена, ждёт подтверждения или отложена
    /// (<see cref="OrgServerStatus"/>). Подключение сервера двустороннее: заявка с одной
    /// стороны обязательно подтверждается на другой — на дирижёре (todo41 п. 7).</summary>
    public string Status { get; set; } = OrgServerStatus.Active;
    /// <summary>Кто подал заявку (имя и почта аккаунта на подключаемом сервере) — показывается
    /// в форме подтверждения.</summary>
    public string RequestedBy { get; set; } = "";
    /// <summary>Свободный комментарий заявки/связи.</summary>
    public string Note { get; set; } = "";

    // --- ЗАЯВИТЕЛЬ (T-139, доработка): заявка анонимная, реквизитов дирижёра у подающего
    // нет — человека называет сама заявка. Подтверждение делает его участником организации:
    // исполнитель заводится со ссылкой на ЭТОТ аккаунт, а сам аккаунт с его паролем приезжает
    // репликацией с подключаемого сервера. Пароли в кластере не выравнивают: аккаунт один.

    /// <summary>Внутренний ключ аккаунта заявителя на подключаемом сервере.</summary>
    public string ApplicantId { get; set; } = "";
    /// <summary>Имя заявителя.</summary>
    public string ApplicantName { get; set; } = "";
    /// <summary>Почта заявителя — она же логин его аккаунта.</summary>
    public string ApplicantEmail { get; set; } = "";
    /// <summary>Хэш пароля заявителя, приехавший с заявкой: им дирижёр заводит человека
    /// с тем же паролем. Стирается сразу после подтверждения — он больше не нужен.</summary>
    public string ApplicantHash { get; set; } = "";

    // --- денормализовано для UI (в таблице не хранится) ---
    public string ServerName { get; set; } = "";
    public string Url { get; set; } = "";
    public bool IsLocal { get; set; }
    public string OrgName { get; set; } = "";
    public string OrgCode { get; set; } = "";

    /// <summary>ЗАЯВИТЕЛЬ УЖЕ ИСПОЛНИТЕЛЬ ЭТОЙ ОРГАНИЗАЦИИ (T-150): имя его исполнителя;
    /// пусто — человек новый, и «ПРИНЯТЬ» заведёт его. Считается при показе заявки: без
    /// исполнителя человек не участник организации, и об этом должен знать тот, кто
    /// принимает решение.</summary>
    public string ApplicantMember { get; set; } = "";
}

/// <summary>
/// Человек, подавший заявку на подключение сервера (T-139, доработка). Заявка АНОНИМНА:
/// реквизитов дирижёра у подающего нет, поэтому имя и почту он называет сам, а <see cref="Id"/> —
/// внутренний ключ его аккаунта на подключаемом сервере. Подтверждение заявки делает этого
/// человека участником организации: исполнитель заводится со ссылкой на этот аккаунт, а сам
/// аккаунт с хэшем пароля приезжает репликацией — второй раз человека заводить не нужно.
/// </summary>
/// <param name="PasswordHash">Хэш пароля аккаунта как он лежит в базе подключаемого сервера:
