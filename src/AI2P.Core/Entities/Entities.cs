/// <summary>
/// ЗАЯВКА НА СМЕНУ ДИРИЖЁРА ОРГАНИЗАЦИИ (T-21-S1).
///
/// Дирижёр — не флажок, который можно переставить у себя: от него зависит, кто выдаёт коды
/// серверам, кто ведёт справочники и с кем реплицируются остальные (ТЗ гл. 6). Поэтому
/// передача дирижёрства — ОТДЕЛЬНАЯ операция и она ДВУСТОРОННЯЯ, как первое подключение
/// сервера: одна сторона подаёт заявку, вторая принимает или отклоняет.
///
/// Подать заявку вправе только две стороны — назначаемый сервер и сегодняшний дирижёр;
/// третий сервер кластера в чужую передачу не вмешивается. Заявка едет второй стороне
/// обычной репликацией (таблица в БД организации), решение возвращается тем же путём.
///
/// АВАРИЙНЫЙ СЛУЧАЙ. Дирижёр может быть потерян физически — тогда принимать заявку некому,
/// и организация осталась бы без дирижёра навсегда. Поэтому у заявки, поданной САМИМ
/// назначаемым сервером, идёт обратный отсчёт (<c>ConductorRequestService.UnilateralAfter</c>,
/// 12 часов): по его истечении назначаемый сервер вправе принять её
/// В ОДНОСТОРОННЕМ ПОРЯДКЕ. Заявка,
/// поданная дирижёром, такой возможности не даёт — там вторая сторона заведомо жива.
/// </summary>
public sealed class ConductorRequest : Entity
{
    /// <summary>Кого назначают дирижёром (внутренний ключ сервера).</summary>
    public string TargetServerId { get; set; } = "";

    /// <summary>Сегодняшний дирижёр организации на момент подачи — он вторая сторона,
    /// если заявку подал назначаемый сервер. Пусто — дирижёра не было вовсе.</summary>
    public string FromServerId { get; set; } = "";

    /// <summary>Кто ПОДАЛ заявку: либо <see cref="TargetServerId"/>, либо
    /// <see cref="FromServerId"/> — третья сторона подать её не может.</summary>
    public string InitiatorServerId { get; set; } = "";

    /// <summary><see cref="ConductorRequestStatus"/>.</summary>
    public string Status { get; set; } = ConductorRequestStatus.Pending;

    /// <summary>Записка подавшего — её читает тот, кто принимает решение.</summary>
    public string Note { get; set; } = "";

    /// <summary>Кто подал заявку словами (имя и почта человека) — для формы решения.</summary>
    public string RequestedBy { get; set; } = "";

    /// <summary>Кто принял решение словами; пусто — решения ещё нет.</summary>
    public string DecidedBy { get; set; } = "";

    /// <summary>Когда принято решение; null — заявка ещё ждёт.</summary>
    public DateTime? DecidedAt { get; set; }

    /// <summary>Заявка принята В ОДНОСТОРОННЕМ ПОРЯДКЕ (дирижёр не отозвался за отведённое
    /// время): для журнала и для формы — это не то же самое, что согласие второй стороны.</summary>
    public bool Unilateral { get; set; }

    /// <summary>Сервер-АВТОР строки (ТЗ гл. 6) — он же подавший заявку: заводит и убирает её
    /// только он. Решение по заявке пишет вторая сторона — единственное осознанное исключение
    /// из правила одного писателя, см. описание таблицы в <c>Database</c>.</summary>
    public string? ServerId { get; set; }

    // --- денормализовано для UI (в таблице не хранится) ---

    /// <summary>Имя назначаемого сервера.</summary>
    public string TargetServerName { get; set; } = "";

    /// <summary>Код назначаемого сервера в организации (S0, S1, …).</summary>
    public string TargetServerCode { get; set; } = "";

    /// <summary>Имя сегодняшнего дирижёра.</summary>
    public string FromServerName { get; set; } = "";

    /// <summary>Код сегодняшнего дирижёра.</summary>
    public string FromServerCode { get; set; } = "";

    /// <summary>Заявку подал сам назначаемый сервер: только у такой есть обратный отсчёт
    /// и одностороннее принятие (T-21-S1).</summary>
    public bool ByTarget => InitiatorServerId.Length > 0 && InitiatorServerId == TargetServerId;
}

