/// <summary>
/// ПРАВИЛО АРХИВАЦИИ (T-41-S0, выпуск 1.105) — строка таблицы <c>archive_rules</c>: что и
/// какой давности пора уносить в архив. Реплицируется вместе с реестром архивов.
///
/// Групп правил ДВЕ, а состав полей у них ОДИН И ТОТ ЖЕ: общие правила организации
/// (образец, с которого копируются правила нового архива) и правила конкретного архива.
/// Отличает их только <see cref="ArchiveId"/>: пусто — общее правило, заполнено — правило
/// архива. Отдельной колонки-признака нет намеренно: она разъехалась бы со ссылкой молча
/// (та же наука, что у третьего вида записей опыта, T-11-S0).
/// </summary>
public sealed class ArchiveRule : Entity
{
    /// <summary>Архив, которому принадлежит правило; пусто (null) — ОБЩЕЕ правило
    /// организации из справочников настроек.</summary>
    public string? ArchiveId { get; set; }

    /// <summary>Общее правило организации — признак ПРОИЗВОДНЫЙ, в таблице его нет.</summary>
    public bool IsCommon => ArchiveId is not { Length: > 0 };

    /// <summary>Относится к: задачи, шаблоны, объекты, опыт, правила безопасности, логи
    /// (<see cref="AI2P.Core.ArchiveRuleTargets"/>).</summary>
    public string Target { get; set; } = AI2P.Core.ArchiveRuleTargets.Tasks;

    /// <summary>Состояние задачи — ТОЛЬКО у правил про задачи; у остальных видов пусто.</summary>
    public string TaskStatus { get; set; } = "";

    /// <summary>Список состояний ПОТОМКОВ. Пустой список означает «любое состояние»:
    /// иерархия архивируется целиком, и если хотя бы один потомок в список не попал —
    /// архивации не будет вовсе.</summary>
    public List<string> ChildStatuses { get; set; } = [];

    /// <summary>Активность остальных данных (<see cref="AI2P.Core.ArchiveRuleActivity"/>) —
    /// то, что у задач заменяет состояние.</summary>
    public string Activity { get; set; } = AI2P.Core.ArchiveRuleActivity.Any;

    /// <summary>По какой дате считать возраст — создания или изменения
    /// (<see cref="AI2P.Core.ArchiveRuleDates"/>).</summary>
    public string DateField { get; set; } = AI2P.Core.ArchiveRuleDates.Updated;

    /// <summary>Срок временной (дни) или календарный (месяцы и года) —
    /// <see cref="AI2P.Core.ArchiveRuleAges"/>.</summary>
    public string AgeKind { get; set; } = AI2P.Core.ArchiveRuleAges.Days;

    /// <summary>Дней от текущей даты — у ВРЕМЕННОГО срока.</summary>
    public int AgeDays { get; set; }

    /// <summary>Месяцев от текущей даты — у КАЛЕНДАРНОГО срока; 0 — считать только года.</summary>
    public int AgeMonths { get; set; }

    /// <summary>Лет от текущей даты — у КАЛЕНДАРНОГО срока.</summary>
    public int AgeYears { get; set; }

    /// <summary>Правило выключено — отбор кандидатов его не берёт.</summary>
    public bool IsActive { get; set; } = true;

    /// <summary>Граничная дата правила: запись с датой не позже неё по возрасту подходит.</summary>
    public DateTime Threshold(DateTime now) =>
        AI2P.Core.ArchiveAge.Threshold(AgeKind, AgeDays, AgeMonths, AgeYears, now);
}

/// <summary>Источник справочника импортов (ТЗ v1.28, todo30): откуда и как импортировать
/// задачи; параметры (логин, фильтр, ссылки на ключи в секретах) — в ParamsJson.</summary>
/// <summary>
/// Коды видов источников импорта (T-247): значение поля <see cref="ImportSource.Kind"/>.
/// Тем же кодом назван документ подключения (<c>doc/&lt;язык&gt;/import/&lt;вид&gt;.md</c>)
/// и ссылки на секреты вида. Сами правила вида (что за секрет, как разобрать ссылку,
/// что считать задачей) живут у его импортёра в AI2P.Connectors — здесь только коды,
/// чтобы на них можно было сослаться из слоёв, которые импортёров не видят.
/// </summary>
public static class ImportKinds
{
    public const string Trello = "trello";

    /// <summary>Задачи (issues) репозиториев GitHub — T-247, версия 1.89.</summary>
    public const string GitHub = "github";

    /// <summary>Задачи (issues) проектов GitLab — T-249, версия 1.89.</summary>
    public const string GitLab = "gitlab";
