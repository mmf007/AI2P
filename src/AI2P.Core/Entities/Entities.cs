    public TaskKind Kind { get; set; } = TaskKind.Task;
    public string Title { get; set; } = "";
    /// <summary>Путь к описанию .md относительно dataDir (тело — в файле, п. 6.4.4).</summary>
    public string DescriptionPath { get; set; } = "";
    /// <summary>Код состояния из справочника состояний (TaskStatuses / ТЗ v1.37).</summary>
    public string Status { get; set; } = TaskStatuses.Draft;
    /// <summary>
    /// СТАТУС ПО ГОТОВНОСТИ (T-250): код состояния, в который переводится задача, когда
    /// ИИ-агент нормально её завершил. По умолчанию «проверка» (<see cref="TaskStatuses.Review"/>) —
    /// прежнее и единственное до версии 1.90 поведение: результат смотрит человек.
    /// Поставленное здесь «готово» (<see cref="TaskStatuses.Done"/>) означает, что проверять
    /// нечего, и тогда завершение задачи само отпускает задачи, которые она блокировала
    /// (в том числе внутри открытой очереди иерархического запуска, T-6-S1). Ошибка агента
    /// сюда не относится вовсе: она по-прежнему даёт «встал с ошибкой».
    /// <para>Поле показывается в форме ТОЛЬКО у задачи с исполнителем-ИИ (основным или
