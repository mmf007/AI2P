    /// </summary>
    public double? TimeQuality { get; set; }
    /// <summary>0 — низкий, 1 — обычный, 2 — высокий.</summary>
    public int Priority { get; set; } = 1;
    /// <summary>Числовой приоритет (ТЗ v1.26): уточняет уровень — низкий 0–10 (по умолчанию 5),
