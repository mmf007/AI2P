public sealed class ImportSource : Entity
{
    public string Name { get; set; } = "";
    /// <summary>Вид источника: <see cref="ImportKinds"/> — trello, github, gitlab.</summary>
    public string Kind { get; set; } = "trello";
    /// <summary>Параметры вида: {"login": "...", "filter": "...", "keyRef": "trello.apiKey",
    /// "tokenRef": "trello.token"}.</summary>
    public string ParamsJson { get; set; } = "{}";
    public bool IsActive { get; set; } = true;

    /// <summary>Ссылка на ключ у источников, заведённых до v1.65: в params_json её нет,
    /// и подставляется она — общая на всех. Переписывать её нельзя, иначе уже введённое
    /// значение осталось бы лежать по старому адресу.</summary>
    public const string LegacyKeyRef = "trello.apiKey";

    /// <summary>Ссылка на токен у источников, заведённых до v1.65 — см. <see cref="LegacyKeyRef"/>.</summary>
    public const string LegacyTokenRef = "trello.token";

    /// <summary>
    /// Ссылки на ключ и токен НОВОГО источника (ТЗ v1.65, T-123). Сами значения пользователь
    /// вводит кнопками формы и ссылок не видит — но ссылка обязана быть СВОЯ у каждого
    /// источника, иначе два аккаунта Trello делили бы одну пару ключ/токен. Источники,
    /// заведённые раньше, свои ссылки (<see cref="LegacyKeyRef"/>, <see cref="LegacyTokenRef"/>)
    /// сохраняют: они лежат в params_json либо подставляются и не переписываются.
    /// </summary>
    public static (string KeyRef, string TokenRef) DefaultRefs(string kind, string sourceId)
    {
        var prefix = kind.Trim().Length > 0 ? kind.Trim().ToLowerInvariant() : "import";
        var tail = new string(sourceId.Where(char.IsLetterOrDigit).Take(8).ToArray());
        var scope = tail.Length > 0 ? $"{prefix}.{tail}" : prefix;
        return ($"{scope}.apiKey", $"{scope}.token");
    }
}

/// <summary>
/// Соответствие уровня приоритета (0 низкий / 1 обычный / 2 высокий) и числового
/// приоритета (ТЗ v1.26): низкий — 0–10, обычный — 11–20, высокий — от 21.
/// Смена уровня подставляет типовое число (5/15/25), правка числа меняет уровень.
/// </summary>
public static class TaskPriority
{
    public const int DefaultLow = 5;
    public const int DefaultMedium = 15;
    public const int DefaultHigh = 25;

    /// <summary>Типовое число для уровня: низкий 5, обычный 15, высокий 25.</summary>
    public static int NumFor(int level) => level switch
    {
        0 => DefaultLow,
        1 => DefaultMedium,
        _ => DefaultHigh,
    };

    /// <summary>Уровень по числу: 0–10 — низкий, 11–20 — обычный, от 21 — высокий.</summary>
    public static int LevelFor(int num) => num switch
    {
        <= 10 => 0,
        <= 20 => 1,
        _ => 2,
    };
}

