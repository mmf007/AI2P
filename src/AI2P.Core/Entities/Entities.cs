/// <summary>
/// ПРАВИЛО УВЕДОМЛЕНИЯ (T-272) — строка списка «Настройки → Уведомления». Список свой
/// у каждой организации: правило ссылается на её исполнителей, проекты и состояния.
///
/// Правило отвечает на четыре вопроса: ПО ЧЕМУ уведомлять (<see cref="EventKind"/>),
/// ПРО ЧТО (<see cref="ProjectIds"/> — пусто значит «про все проекты»), КОМУ
/// (<see cref="ExecutorIds"/> — пусто значит «всем, кого касается событие») и ЧЕМ
/// (<see cref="Channel"/> — вид уведомления, за ним стоит транспорт).
///
/// На ДУБЛИ правил внимания не обращаем намеренно (по заданию): два подходящих правила —
/// два письма. Складывать их значило бы решать за человека, какое из двух писем важнее.
/// </summary>
public sealed class NotificationRule : Entity
{
    /// <summary>Событие: <see cref="AI2P.Core.NotificationEvents"/> — status / review / due.</summary>
    public string EventKind { get; set; } = AI2P.Core.NotificationEvents.Status;

    /// <summary>Код состояния из справочника — только у события «переведена в состояние»
    /// (<see cref="AI2P.Core.NotificationEvents.Status"/>); у остальных пусто.</summary>
    public string StatusCode { get; set; } = "";

    /// <summary>За сколько минут до срока уведомлять — только у события «подходит срок»
    /// (<see cref="AI2P.Core.NotificationEvents.Due"/>); в форме вводится как часы:минуты.
    /// 0 — уведомить в момент наступления срока.</summary>
    public int LeadMinutes { get; set; }

    /// <summary>Вид уведомления: <see cref="AI2P.Core.NotificationChannels"/>.</summary>
    public string Channel { get; set; } = AI2P.Core.NotificationChannels.Mail;

    /// <summary>Шаблон заголовка письма — с макроподстановками (<see cref="AI2P.Core.NotificationMacros"/>).</summary>
    public string Subject { get; set; } = "";

    /// <summary>Шаблон тела письма — с теми же макроподстановками.</summary>
    public string Body { get; set; } = "";

    /// <summary>Неактивное правило не срабатывает; строка остаётся в списке.</summary>
    public bool IsActive { get; set; } = true;

    /// <summary>Исполнители, которых правило касается; ПУСТО — всех, кого касается событие.</summary>
    public List<string> ExecutorIds { get; set; } = [];

    /// <summary>Проекты, задачи которых правило касается; ПУСТО — все проекты организации.</summary>
    public List<string> ProjectIds { get; set; } = [];

    /// <summary>
    /// Сервер правила (ТЗ гл. 6, этап 42): на нём правило правится. Уведомление при этом
    /// отправляет ВЛАДЕЛЕЦ ЗАДАЧИ — тот сервер, где событие произошло, — иначе одно и то же
    /// письмо ушло бы столько раз, сколько в организации серверов.
    /// </summary>
    public string? ServerId { get; set; }
    /// <summary>Код сервера правила (S0, S1, …); в таблице не хранится.</summary>
    public string ServerCode { get; set; } = "";
    /// <summary>Имя сервера правила; в таблице не хранится.</summary>
    public string ServerName { get; set; } = "";
    /// <summary>Правило принадлежит другому серверу — только чтение (ТЗ гл. 6).</summary>
    public bool IsReadOnly { get; set; }
}

/// <summary>
/// АРХИВ ОРГАНИЗАЦИИ (T-40-S0, выпуск 1.105) — запись реестра <c>archives</c>. Реплицируется:
/// список архивов один на всю организацию. Состояние на КОНКРЕТНОМ сервере
