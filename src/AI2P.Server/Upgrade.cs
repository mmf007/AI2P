using AI2P.Core;
using AI2P.Core.Entities;
using AI2P.Server.Org;
using AI2P.Storage;
using Serilog;

namespace AI2P.Server;

/// <summary>
/// ОДНОРАЗОВЫЕ ШАГИ ОБНОВЛЕНИЯ (ТЗ гл. 4.3, этап 46).
///
/// Скрипт установки (<c>install.ps1</c> / <c>install.sh</c>) кладёт новую выкладку поверх
/// старой и данных не трогает: чинить данные в скрипте, не запуская приложение, — верный
/// способ получить полусломанную базу. Поэтому всё, что нужно доделать после обновления,
/// приложение делает САМО при первом старте новой версии.
///
/// Номер последнего отработавшего билда лежит в серверной БД (<c>meta.app_build</c>). При
/// старте выполняются шаги, чей билд больше записанного и не больше текущего; после этого
/// записывается текущий билд. На ЧИСТОЙ установке шаги не выполняются вовсе — конвертировать
/// нечего, просто запоминается билд.
///
/// ОБНОВЛЕНИЕ ЧЕРЕЗ НЕСКОЛЬКО ВЕРСИЙ (T-183) устроено этим же механизмом и ничем не отличается
/// от обновления на одну: выкладка полная, а не заплатка, поэтому пропустить можно сколько
/// угодно версий — при первом старте выполнятся ВСЕ шаги промежуточных билдов по возрастанию.
/// Отсюда требование к шагу: он обязан быть ИДЕМПОТЕНТНЫМ и не полагаться на то, что данные
/// оставила ровно предыдущая версия — между его билдом и установленным может лежать десяток
/// других. Установка, заведённая ДО появления самой отметки билда, разбирается тем же
/// правилом — см. <see cref="Run"/>.
///
/// СТРУКТУРА БАЗЫ здесь не меняется: схема доводится идемпотентными миграциями в
/// <c>Database.Init</c> (<c>meta.schema_version</c>) и работает одинаково при обновлении
/// и на пустой базе. Сюда попадает то, что миграцией не выражается: перенос данных между
/// таблицами, правка файлов на диске, пересчёт чего-либо.
///
/// ПРАВИЛО ДЛЯ НОВОГО ЗАДАНИЯ: если <c>todo&lt;xx&gt;.md</c> требует разовой переделки уже
/// накопленных данных — добавить сюда шаг с номером билда <c>xx</c>. Порядок работ целиком —
/// <c>doc/AI2P_release.md</c>.
/// </summary>
public static class Upgrade
{
    /// <summary>Ключ в <c>meta</c> серверной БД: билд, до которого данные уже доведены.</summary>
    public const string BuildKey = "app_build";

    /// <summary>
    /// Билд, который приписывается установке С ДАННЫМИ, но БЕЗ отметки в <c>meta</c>: сама
    /// отметка появилась в билде 46, и всё, что старше, о ней не знает. Докуда доведены такие
    /// данные, узнать неоткуда, поэтому ответ единственный безопасный — «ни докуда»:
    /// выполняются все шаги, они для того и обязаны быть идемпотентными.
    /// </summary>
    public const int UnknownBuild = 0;

    /// <summary>Один шаг обновления: номер билда, в котором он появился, и что он делает.</summary>
    public sealed record Step(int Build, string Title, Action<OrgRegistry> Run);

    /// <summary>
    /// Шаги обновления по возрастанию билда. Пусто — значит ни одно из заданий до текущего
    /// не потребовало разовой переделки данных: всё, что понадобилось схеме, сделали миграции
    /// (<c>Database.Init</c>), а репликация и справочники доводятся сами при открытии
    /// организации (<c>OrgContext.SeedAndMigrate</c>).
    /// </summary>
    public static readonly Step[] Steps =
    [
        // T-146: приём заявки на подключение сервера мог оборваться на середине — связь уже
        // подтверждена, а заявитель участником организации так и не стал. В интерфейсе это
        // не чинится: заявки в списке больше нет. Доводим до конца при первом старте
        new Step(73, "довести до конца подтверждённые заявки на подключение серверов",
            registry =>
            {
                var done = registry.FinishAcceptedJoins();
                if (done > 0)
                {
                    Log.Information("AI2P: доделано подключений серверов: {Count}", done);
                }
            }),

        // T-153: у подключённых серверов интервал репликации мог остаться пустым — это
        // «только по кнопке», и пара молчала, сколько её ни жди. Теперь интервал задаёт само
        // подключение; уже подключённым парам проставляем его здесь, заданное человеком
        // не трогая
        new Step(75, "включить автоматическую репликацию у подключённых серверов",
            registry =>
            {
                var started = 0;
                foreach (var org in registry.Orgs.List(includeInactive: true))
                {
                    foreach (var link in registry.Servers.ServersOf(org.Id, includeRequests: false))
                    {
                        // интервал принадлежит записи РЯДОВОГО сервера пары (ТЗ гл. 6)
                        if (link.Status != OrgServerStatus.Active || link.IsConductor
                            || link.DeletedAt is not null)
                        {
                            continue;
                        }
                        if (registry.Servers.Get(link.ServerId) is { ReplIntervalSec: null })
                        {
                            registry.Servers.EnsureReplication(link.ServerId, actorId: null);
                            started++;
                        }
                    }
                }
                if (started > 0)
                {
                    Log.Information("AI2P: автоматическая репликация включена у серверов: {Count}",
                        started);
                }
            }),

        // T-185: состояние «ждёт ответа» стало «паузой» — ждать теперь можно не только ответа
        // человека, но и ответа агента соседней задачи, и завершения своих подзадач. Код
        // состояния сменился (waiting_reply → paused), поэтому уже накопленные задачи надо
        // перевести: сама запись справочника приезжает сидом, а вот задачи со старым кодом
        // остались бы «состоянием без названия». Шаг идемпотентен и на чистой базе не делает
        // ничего — переводить нечего
        new Step(80, "перевести задачи из состояния «ждёт ответа» в «пауза»",
            registry =>
            {
                var moved = 0;
                foreach (var org in registry.Orgs.List(includeInactive: true))
                {
                    moved += registry.Context(org).TaskStatuses.MigrateWaitingReplyToPaused();
                }
                if (moved > 0)
                {
                    Log.Information("AI2P: задач переведено в состояние «пауза»: {Count}", moved);
                }
            }),

        // T-227: рядовой сервер присваивал себе облачные записи справочника моделей —
        // пересчёт признака размещения зовётся на каждом старте, в том числе на реплике,
        // и заодно проставлял владельца. На дирижёре такие записи становились чужими и
        // переставали правиться, а интерфейсом это не чинится. Возвращаем их в общую часть
        // справочника. Шаг идемпотентен: чинит СОСТОЯНИЕ, а не разницу между версиями, —
        // при повторном старте находить уже нечего. Правка идёт обычной записью, поэтому
        // уезжает партнёру ближайшим сеансом; если её сделали обе стороны, значения совпадают
        // и сливаются молча
        new Step(85, "вернуть облачные записи справочника моделей в общую часть",
            registry =>
            {
                var freed = 0;
                foreach (var org in registry.Orgs.List(includeInactive: true))
                {
                    var conductor = registry.Servers.ServersOf(org.Id, includeRequests: false)
                        .FirstOrDefault(l => l.IsConductor && l.DeletedAt is null)?.ServerId ?? "";
                    freed += registry.Context(org).Models.ReleaseStolenCloudRecords(
                        conductor, id => registry.Servers.CodeOf(org.Id, id));
                }
                if (freed > 0)
                {
                    Log.Information("AI2P: записей справочника моделей возвращено "
                                    + "в общую часть: {Count}", freed);
                }
            }),

        // T-3-S1: журнал изменений считал время в миллисекундах, а состав команды и связи
        // задачи сохраняются приёмом «снести все строки и вставить заново» — обе записи
        // попадали в одну миллисекунду, получали одинаковые часы, и партнёр принимал только
        // удаление. На втором сервере из команд и задач пропадала часть исполнителей, тэгов
        // и навыков. Часы исправлены, но курсор партнёра давно ушёл вперёд: строки, у которых
        // в журнале есть два изменения с одинаковыми часами, называем заново. Шаг идемпотентен
        // и чинит СОСТОЯНИЕ, а не разницу версий; выполнить его обязаны ОБЕ стороны пары —
        // каждая называет заново свои строки
        new Step(86, "назвать партнёру заново строки, потерянные из-за совпавших часов журнала",
            registry =>
            {
                var resent = ChangeLog.ResendTiedRows(registry.ServerDb);
                foreach (var org in registry.Orgs.List(includeInactive: true))
                {
                    resent += ChangeLog.ResendTiedRows(registry.Context(org).Db);
                }
                if (resent > 0)
                {
                    Log.Information("AI2P: строк названо партнёру заново: {Count}", resent);
                }
            }),

        // T-246: у задачи появилась ССЫЛКА ИМПОРТА — адрес, откуда она приехала; по ней
        // работает кнопка «обновить из источника». Задачи, импортированные прошлыми
        // версиями, знают только внутренний ключ карточки («trello:<id>»), а человеческий
        // адрес у них сохранился в одном месте — в описании, куда импорт его и дописал.
        // Оттуда и берём. Шаг ИДЕМПОТЕНТЕН: задачи с уже заполненной ссылкой не трогаются,
        // и при повторном старте находить нечего; на чистой установке он не делает ничего
        new Step(89, "проставить ссылку импорта уже импортированным задачам",
            registry =>
            {
                var filled = 0;
                foreach (var org in registry.Orgs.List(includeInactive: true))
                {
                    filled += registry.Context(org).Tasks.FillImportUrlsFromDescriptions();
                }
                if (filled > 0)
                {
                    Log.Information("AI2P: ссылка импорта проставлена задачам: {Count}", filled);
                }
            }),

        // T-274: кадры обучения перестали быть прямыми детьми объекта и стали детьми
        // ДАТАСЕТА — отдельного дочернего объекта. Иначе у объекта, у которого есть свои
        // логические дети, иерархия превращалась в кашу: полсотни картинок вперемешку с
        // осмысленными объектами. Уже накопленные кадры переносим в датасет, заведённый
        // умолчанием, и делаем его текущим. Шаг ИДЕМПОТЕНТЕН и чинит СОСТОЯНИЕ: объект,
        // у которого датасет уже есть, не трогается вовсе, — поэтому повторный старт
        // находить нечего, а на чистой установке он не делает ничего. Работать без него
        // система умеет: обучение объекта без датасетов идёт по прямым детям, как раньше
        new Step(98, "перенести кадры обучения LoRA в датасет",
            registry =>
            {
                var moved = 0;
                foreach (var org in registry.Orgs.List(includeInactive: true))
                {
                    moved += registry.Context(org).Objects.MoveLegacyFramesToDatasets(
                        AI2P.Core.Loc.T("msg.lora.28"));
                }
                if (moved > 0)
                {
                    Log.Information("AI2P: объектов, чьи кадры перенесены в датасет: {Count}",
                        moved);
                }
            }),
        // T-98-S0: подрезанные кадры датасетов LoRA лежали в ПАПКЕ ПРОЕКТА, а она у каждого
        // сервера своя и не реплицируется — на соседнем сервере датасет был пуст. Переносим
        // их в каталог данных организации, который едет партнёру целиком. Шаг ИДЕМПОТЕНТЕН:
        // кадр, уже лежащий в хранилище, пропускается; кадр, файла которого на этом сервере
        // нет, не трогается вовсе — его перенесёт тот сервер, у которого файл есть
        new Step(112, "перенести кадры датасетов LoRA в хранилище организации",
            registry =>
            {
                var moved = 0;
                foreach (var org in registry.Orgs.List(includeInactive: true))
                {
                    var context = registry.Context(org);
                    moved += context.Objects.MoveFramesToStore(context.Files, context.Projects);
                }
                if (moved > 0)
                {
                    Log.Information("AI2P: кадров датасетов, перенесённых в хранилище: {Count}",
                        moved);
                }
            }),

        // T-216-S0: обход производителей показал, что две записи справочника рынок обогнал —
        // Gemini-3-Ultra и Gemini-3.1-Pro (у обеих больше трёх более старших версий того же
        // семейства, а их идентификаторов в публичном каталоге моделей уже нет). Гасим, а не
        // удаляем: на записи ссылаются исполнители, прошлые задания и отчёты. На ЧИСТОЙ
        // установке то же самое делает сам сид (AiModelService.RetiredSeedModels); шаг нужен
        // тем, у кого записи уже заведены и активны. Разовый: включить обратно галочкой
        // «активна» человек по-прежнему может, и второй раз шаг её не погасит
        new Step(132, "погасить записи справочника моделей, устаревшие по версиям",
            registry =>
            {
                var retired = 0;
                foreach (var org in registry.Orgs.List(includeInactive: true))
                {
                    retired += registry.Context(org).Models.RetireOutdatedSeedModels();
                }
                if (retired > 0)
                {
                    Log.Information("AI2P: погашено устаревших записей справочника моделей: {Count}",
                        retired);
                }
            }),
    ];

    /// <summary>
    /// Выполнить шаги, нужные для перехода на текущий билд, и запомнить его.
    /// Возвращает число выполненных шагов.
    /// </summary>
    /// <param name="registry">Реестр организаций: через него шаг добирается и до серверной
    /// БД, и до данных каждой организации.</param>
    /// <param name="steps">Список шагов; null — <see cref="Steps"/> (параметр для тестов).</param>
    public static int Run(OrgRegistry registry, Step[]? steps = null)
    {
        steps ??= Steps;
        var stored = registry.ServerDb.Meta(BuildKey);
        int from;
        if (stored is null)
        {
            if (IsFreshInstall(registry))
            {
                // чистая установка: конвертировать нечего, просто фиксируем билд
                registry.ServerDb.SetMeta(BuildKey, AppInfo.Build.ToString());
                return 0;
            }
            // данные есть, а отметки нет — установка старше билда 46, где отметку завели
            // (T-183). Считать её «чистой», как делалось раньше, нельзя: так пропускались
            // ВСЕ шаги обновления разом, и молча — именно на том обновлении, где через них
            // перепрыгнули дальше всего
            from = UnknownBuild;
            Log.Warning("AI2P: в данных нет отметки билда — установка старше {Since}; "
                        + "выполняются все шаги обновления", 46);
        }
        else if (!int.TryParse(stored, out from))
        {
            from = UnknownBuild;
        }
        if (from == AppInfo.Build)
        {
            return 0;
        }
        if (from > AppInfo.Build)
        {
            // запустили СТАРУЮ версию поверх данных новой — шаги не откатываются, и делать
            // вид, что всё в порядке, нельзя: пусть это будет видно в логе
            Log.Warning("AI2P: данные обновлены до билда {Stored}, а запущен билд {Current} — "
                        + "возможна несовместимость; поставьте версию не ниже {Stored}",
                stored, AppInfo.Build, stored);
            return 0;
        }

        Log.Information("AI2P: обновление данных с билда {From} до {To}", from, AppInfo.Build);
        var done = 0;
        // докуда данные доведены на самом деле: нужно сообщению об упавшем шаге
        var reached = from;
        foreach (var step in steps.Where(s => s.Build > from && s.Build <= AppInfo.Build)
                     .OrderBy(s => s.Build))
        {
            Log.Information("AI2P: шаг обновления {Build} — {Title}", step.Build, step.Title);
            try
            {
                step.Run(registry);
            }
            catch (Exception ex)
            {
                // упавший шаг останавливает старт (исключение уходит наверх, в Program.cs):
                // работать на данных, доведённых до середины, хуже, чем не запуститься.
                // Но в логе должно быть НАЗВАНО, что именно не получилось, — иначе после
                // прыжка через десяток версий человек видит только «аварийное завершение»
                Log.Error(ex, "AI2P: шаг обновления {Build} ({Title}) не выполнен; данные "
                              + "доведены до билда {Done}, при следующем старте шаг повторится",
                    step.Build, step.Title, reached);
                throw;
            }
            done++;
            reached = step.Build;
            // билд записывается ПОСЛЕ каждого шага: прерванное обновление продолжится
            // с того места, где остановилось, а не начнётся заново
            registry.ServerDb.SetMeta(BuildKey, step.Build.ToString());
        }
        registry.ServerDb.SetMeta(BuildKey, AppInfo.Build.ToString());
        return done;
    }

    /// <summary>
    /// Билд, С КОТОРОГО обновляется эта установка, — то самое число, по которому
    /// <see cref="Run"/> отбирает шаги. <c>null</c> — обновлять нечего: либо установка
    /// чистая, либо данные уже доведены до текущего билда (или запущена версия постарше).
    ///
    /// Нужен разовым правкам ВНЕ данных организации: шаг обновления получает только реестр,
    /// а <c>config.json</c> живёт рядом с программой (T-215-S0 — включить «доверять
    /// сертификату соседей» тем, кто обновляется со старым значением в файле). Спрашивать
    /// ДО <see cref="Run"/>: он перезаписывает отметку.
    /// </summary>
    public static int? UpgradingFrom(OrgRegistry registry)
    {
        var stored = registry.ServerDb.Meta(BuildKey);
        if (stored is null)
        {
            // отметки нет: чистая установка — обновлять нечего, иначе установка старше
            // билда 46, и доведена она «ни докуда» (см. Run)
            return IsFreshInstall(registry) ? null : UnknownBuild;
        }
        if (!int.TryParse(stored, out var from))
        {
            from = UnknownBuild;
        }
        return from >= AppInfo.Build ? null : from;
    }

    /// <summary>
    /// Установка ЧИСТАЯ: базу только что создали, и доводить в ней нечего (T-183).
    ///
    /// Признак — ни одного аккаунта и ни одной организации: и то и другое заводит человек
    /// (визард первого старта, ТЗ гл. 11) или подключение к чужому дирижёру, а к моменту
    /// первого вызова <see cref="Run"/> на новой установке не сделано ни того, ни другого.
    /// Запись о ЛОКАЛЬНОМ сервере признаком служить не может: её создаёт сам старт, до этого
    /// вызова, и на чистой установке она есть всегда.
    /// </summary>
    public static bool IsFreshInstall(OrgRegistry registry) =>
        registry.Accounts.List(includeDeleted: true).Count == 0
        && registry.Orgs.List(includeInactive: true).Count == 0;
}
